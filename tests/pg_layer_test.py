"""pg_layer_test.py -- 2.37.0 (#1150): the Postgres driver layer (kalmido/core/pg.py) on its own, inside the test container.

Placeholder translation (literals, comments, dollar quotes, % signs, `? IS NULL`), the row type (index, name, keys(), dict()),
SQLite-like parameter typing (ints / bools as untyped literals, NUMERIC back as int / float, jsonb as text), insert_id,
savepoints after a failed statement, write_lock across two connections, the request context (set per transaction, kept after
commit, never handed to the next borrower of a pooled connection).
Run (container from start.sh):  python3 tests/pg_layer_test.py [datadir]
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, ".data")
CONTAINER = os.environ.get("KALMIDO_TEST_CONTAINER", "kalmido-test")

CODE = r'''
import os, threading, time
from kalmido.core import pg
from kalmido.core.config import DATABASE_URL
fails = []
def check(ok, msg):
    print(("ok  " if ok else "FAIL") + " " + msg)
    if not ok: fails.append(msg)

t = pg.translate
check(t("SELECT ? WHERE a=?") == "SELECT %t WHERE a=%t", "? -> %t")
check(t("SELECT '?', '%', \"a?\" FROM x WHERE b LIKE '%x%' AND c=?") == "SELECT '?', '%%', \"a?\" FROM x WHERE b LIKE '%%x%%' AND c=%t", "literals keep ?, % doubled")
check(t("SELECT 'it''s ?' , ?") == "SELECT 'it''s ?' , %t", "doubled quote inside a literal")
check(t("SELECT 1 -- what? 5%\n, ?") == "SELECT 1 -- what? 5%%\n, %t", "comment keeps ?")
check(t("SELECT $fn$ a ? b $fn$, ?") == "SELECT $fn$ a ? b $fn$, %t", "dollar quote keeps ?")
check(t("SELECT 1 WHERE ? IS NULL OR x=?") == "SELECT 1 WHERE %t::text IS NULL OR x=%t", "? IS NULL gets a type")
check(t("SELECT 5 % 2, ?") == "SELECT 5 %% 2, %t", "modulo operator")

c = pg.connect_direct(DATABASE_URL)
c.execute("CREATE TEMP TABLE plt (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n BIGINT, s TEXT UNIQUE, "
          "j JSONB, m NUMERIC(14,4), d DOUBLE PRECISION, b BYTEA)")
i1 = pg.insert_id(c, "INSERT INTO plt(n,s,j,m,d,b) VALUES(?,?,?,?,?,?)", (True, 7, '{"k": [1, 2]}', 12.5, 3, b"\x00\x01"))
i2 = pg.insert_id(c, "INSERT INTO plt(n,s,m) VALUES(?,?,?);", ("41", "x", 3))
check(isinstance(i1, int) and i2 == i1 + 1, f"insert_id returns the new ids ({i1}, {i2})")
r = c.execute("SELECT * FROM plt WHERE id=?", (i1,)).fetchone()
check(r[0] == i1 and r["n"] == 1 and r["N"] == 1 and r["s"] == "7", "row by index / name (any case); True stored as 1, int into TEXT")
check(r.keys() == ["id", "n", "s", "j", "m", "d", "b"] and dict(r)["m"] == 12.5, "keys() and dict()")
check(isinstance(r["j"], str) and '"k"' in r["j"], "jsonb comes back as JSON text")
m2 = c.execute("SELECT m FROM plt WHERE id=?", (i2,)).fetchone()[0]
check(r["m"] == 12.5 and m2 == 3.0 and isinstance(m2, float), "NUMERIC column -> float like REAL (3 -> 3.0)")
check(isinstance(c.execute("SELECT COUNT(*) + SUM(n) FROM plt").fetchone()[0], int), "whole NUMERIC results -> int")
check(bytes(r["b"]) == b"\x00\x01", "bytea")
check(c.execute("SELECT SUM(n) FROM plt").fetchone()[0] == 42, "SUM(bigint) is an int")
check(c.execute("SELECT COUNT(*) FROM plt WHERE (? IS NULL OR s=?)", (None, "x")).fetchone()[0] == 2, "? IS NULL with None")
check(c.execute("SELECT COUNT(*) FROM plt WHERE n=?", ("41",)).fetchone()[0] == 1, "a str parameter against BIGINT")
try:
    r.nope
    check(False, "unknown attribute")
except AttributeError:
    pass
try:
    r["nope"]
    check(False, "unknown key raises")
except IndexError:
    check(True, "unknown key raises IndexError like sqlite3.Row")
# a failed statement inside a savepoint leaves the transaction usable
try:
    with c.savepoint():
        c.execute("INSERT INTO plt(s) VALUES(?)", ("x",))
    check(False, "duplicate refused")
except pg.IntegrityError:
    check(True, "duplicate raises IntegrityError")
check(c.execute("SELECT COUNT(*) FROM plt").fetchone()[0] == 2, "transaction still usable after the savepoint")
c.commit()

# request context: kept after commit, gone for the next borrower of a pooled connection
c.set_ctx(7, (3, 4), "user")
v = lambda cc: tuple(cc.execute("SELECT current_setting('app.user_id', true), current_setting('app.org_ids', true), current_setting('app.role', true)").fetchone())
check(v(c) == ("7", "3,4", "user"), "context set")
c.commit()
check(v(c) == ("7", "3,4", "user"), "context set again after commit")
c.rollback()
check(v(c) == ("7", "3,4", "user"), "context set again after rollback")
c.close()
p1 = pg.connect_pooled(DATABASE_URL); p1.set_ctx(9, (1,), "agent"); a = v(p1); pid = p1.execute("SELECT pg_backend_pid()").fetchone()[0]; p1.close()
seen = None
for _ in range(30):  # borrow until the same server connection comes back
    p2 = pg.connect_pooled(DATABASE_URL)
    if p2.execute("SELECT pg_backend_pid()").fetchone()[0] == pid:
        seen = v(p2)
        p2.close()
        break
    p2.close()
check(a == ("9", "1", "agent"), "pooled context")
check(seen is None or seen == ("", "", "system"), f"a reused pooled connection starts as system ({seen})")

# write_lock: the second writer waits for the first
c1, c2 = pg.connect_direct(DATABASE_URL), pg.connect_direct(DATABASE_URL)
pg.write_lock(c1, "pltest")
order = []
def other():
    pg.write_lock(c2, "pltest"); order.append("c2"); c2.commit()
th = threading.Thread(target=other); th.start(); time.sleep(0.5)
order.append("c1"); c1.commit(); th.join(5)
check(order == ["c1", "c2"], f"write_lock serializes ({order})")
c1.close(); c2.close()
print("FAILED", len(fails) if fails else "") if fails else print("pg_layer: ok, 0 failed")
raise SystemExit(1 if fails else 0)
'''

p = subprocess.run(["docker", "exec", "-i", "-w", "/app", CONTAINER, "python", "-"], input=CODE, capture_output=True, text=True,
                   timeout=120)
print(p.stdout + p.stderr)
sys.exit(p.returncode)
