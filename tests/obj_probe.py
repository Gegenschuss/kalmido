"""2.558.0 (#4709): helpers of the core suites (tests/obj_core_test.py, tests/obj_write_test.py) -- not a suite itself.

The test container registers the kind 'objprobe' (KALMIDO_TEST_OBJ=1, kalmido/core/objects.py _probe_register) on the table
obj_probe, which only these suites create (TABLE_SQL, through tests/dbx.py): the columns every core table has plus the
fields title / note / size / done."""
import requests

from kt import B, H, dbx, fresh

K = "objprobe"
ENV = {"KALMIDO_TEST_OBJ": "1"}
TABLE_SQL = """CREATE TABLE IF NOT EXISTS obj_probe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, rev BIGINT NOT NULL DEFAULT 1, created_at TEXT NOT NULL,
  created_by BIGINT, updated_at TEXT NOT NULL, updated_by BIGINT, deleted_at TEXT, deleted_by BIGINT,
  title TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '', size BIGINT, done BIGINT NOT NULL DEFAULT 0)"""


def start(prefix):
    """A fresh container with the test kind, and its table."""
    fresh(env=ENV, prefix=prefix)
    dbx(TABLE_SQL)


def new(s, title, org=None, **kw):
    """A new object as session s -> its JSON (asserts 201)."""
    r = s.post(B + f"/api/obj/{K}", json={"title": title, **({"org_id": org} if org else {}), **kw})
    assert r.status_code == 201, (title, r.status_code, r.text[:300])
    return r.json()


def role(s, oid):
    """The role session s has on object oid, or the status code."""
    r = s.get(B + f"/api/obj/{K}/{oid}")
    return r.json().get("role") if r.ok else r.status_code


def ids(s, trash=False):
    r = s.get(B + f"/api/obj/{K}", params={"trash": "1"} if trash else None)
    return sorted(x["id"] for x in r.json()["items"]) if r.ok else r.status_code


class Agent:
    """An agent's token on the agent routes (/api/v1/agent/objects/...)."""

    def __init__(self, aid, token):
        self.id, self.h = aid, {**H, "Authorization": "Bearer " + token}

    def get(self, oid=None):
        return requests.get(B + f"/api/v1/agent/objects/{K}" + (f"/{oid}" if oid else ""), headers=self.h, timeout=30)

    def patch(self, oid, body):
        return requests.patch(B + f"/api/v1/agent/objects/{K}/{oid}", headers=self.h, json=body, timeout=30)

    def role(self, oid):
        r = self.get(oid)
        return r.json().get("role") if r.ok else r.status_code


def agent(s, name, org=None, scopes=("read", "tasks:write")):
    """A new agent of session s (org: an organisation's agent) -> Agent."""
    r = s.post(B + "/api/my/agents", json={"username": name, "display_name": name.title(), "scopes": list(scopes), **({"org_id": org} if org else {})})
    assert r.ok, (name, r.status_code, r.text[:300])
    return Agent(r.json()["id"], r.json()["token"])
