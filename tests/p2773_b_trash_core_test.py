#!/usr/bin/env python3
# kalmido-suite: fresh
"""2.773.0 (#5292): ONE trash in the core (kalmido/core/writes.py obj_trash / obj_restore / obj_purge / obj_trash_prune) with
the test kind 'objprobe' (KALMIDO_TEST_OBJ=1) and its children (KALMIDO_TEST_OBJ_PARTS=1: table obj_probe_part, made here with
a TEXT deleted_at while the object's is TIMESTAMPTZ). Invented names only.
 - into the trash: the object and its live children with the same time; a child in the trash on its own before keeps its time
 - rights: a member (edit) 403 on trash / restore / delete, another organisation and a person without one 404
 - the step can be taken back from the list of steps (GET /api/undo, POST /api/undo/to/<id>): out of the trash with the
   children that went with it, redo puts it back; a restore is a step too; restored by someone else meanwhile = the part stays (409)
 - delete for good only from the trash (409 before), children, history and undo steps go with it, the step groups are recounted
 - the retention run: obj_trash_prune counts (switch off) or deletes what is in the trash longer than the period, not the
   younger ones; obj_trash_tick reports it (ret_last_trash.obj_trash); the calendars' run goes through the same core path
 - live_sql / trash_sql (core/access.py): the condition with an alias, a wrong alias / column = ValueError
 - 2.778.0 (#5371): a kind with trash_role 'edit' (objprobe_e): a member who put it into the trash takes that own step back
   (/api/undo), the trash's restore stays at manage; another person's trash meanwhile is not taken out by the old step
tenant-matrix: obj (another organisation: 404 on trash / restore / delete of an object, no undo of a foreign step)
freelancer-matrix: obj (a person without an organisation: her object with children into the trash, undone, deleted for good)
usage: p2773_b_trash_core_test.py <datadir>"""
import json
import os
import sys

N = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, N)
from freelancer_fixture import freelancer  # noqa: E402
from kt import B, check, dbx, done, fresh, sess  # noqa: E402
from obj_probe import ENV, K, TABLE_SQL, in_app, new  # noqa: E402

PART_SQL = """CREATE TABLE IF NOT EXISTS obj_probe_part (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, probe_id BIGINT NOT NULL, name TEXT NOT NULL DEFAULT '', deleted_at TEXT)"""
fresh(env={**ENV, "KALMIDO_TEST_OBJ_PARTS": "1"}, prefix="P2773B")
for q in (TABLE_SQL, PART_SQL, "GRANT SELECT, INSERT, UPDATE, DELETE ON obj_probe, obj_probe_part TO kalmido_app",
          "GRANT USAGE, SELECT ON SEQUENCE obj_probe_id_seq, obj_probe_part_id_seq TO kalmido_app"):
    dbx(q)

assert sess().post(B + "/api/auth/setup", json={"username": "alice", "display_name": "Alice", "password": "password123"}).ok
A = sess("alice")
A.post(B + "/api/admin/setup", json={"org_name": "Example Studio", "lang": "en", "collab_all": True, "modules": ["cal", "comments", "collab"]})
A.patch(B + "/api/settings", json={"tour": "done", "lang": "en"})
ORG = A.get(B + "/api/state").json()["me"]["workspaces"][0]["id"]
uid = {}
for u in ("bob", "carl"):
    r = A.post(B + "/api/users", json={"orgs": [{"id": ORG, "role": "member"}], "username": u, "display_name": u.title(),
                                       "password": "password123", "email": f"{u}@example.com"})
    uid[u] = r.json().get("id")
r = A.post(B + "/api/users", json={"orgs": [], "username": "olga", "display_name": "Olga", "password": "password123", "email": "olga@example.com"})
uid["olga"] = r.json().get("id")
check(A.post(B + "/api/admin/orgs", json={"name": "Other Example", "admin_id": uid["olga"]}).ok, "setup: another organisation")
Bo, Ca, Ol = sess("bob"), sess("carl"), sess("olga")
for s in (Bo, Ca, Ol):
    s.patch(B + "/api/settings", json={"tour": "done", "lang": "en"})
BOB = uid["bob"]
FID, Fr = freelancer(B, A)
OLD = "2026-01-02T03:04:05+00:00"


def parts(oid):
    """{name: deleted_at as text or None} of the object's children."""
    return {r[0]: r[1] for r in dbx("SELECT name, deleted_at FROM obj_probe_part WHERE probe_id=? ORDER BY id", (oid,))}


def with_parts(s, title, org=None):
    oid = new(s, title, org)["id"]
    for nm in ("a", "b"):
        dbx("INSERT INTO obj_probe_part(probe_id, name) VALUES(?, ?)", (oid, nm))
    dbx("INSERT INTO obj_probe_part(probe_id, name, deleted_at) VALUES(?, 'own', ?)", (oid, OLD))  # in the trash on its own
    return oid


def same_time(oid):
    """The children that went with it carry the object's time (TEXT against TIMESTAMPTZ, compared as points in time)."""
    return dbx("SELECT COUNT(*) FROM obj_probe_part p JOIN obj_probe o ON o.id=p.probe_id WHERE o.id=? AND p.name<>'own' "
               "AND CAST(p.deleted_at AS TIMESTAMPTZ)=o.deleted_at", (oid,))[0][0]


def groups(u):
    return dbx("SELECT id, state, parts, label_key FROM undo_groups WHERE user_id=? ORDER BY id", (u,))


def modes(gid):
    return [r[0] for r in dbx("SELECT mode FROM obj_undo WHERE group_id=? ORDER BY id", (gid,))]


def gone(oid):
    return not dbx("SELECT 1 FROM obj_probe WHERE id=?", (oid,))


# ---------------------------------------------------------------- into the trash, with the children; the rights
O1 = with_parts(Bo, "Plan", ORG)
check(Ca.post(B + f"/api/obj/{K}/{O1}/trash").status_code == 403, "a member (edit): no trash (403)")
check(Ol.post(B + f"/api/obj/{K}/{O1}/trash").status_code == 404, "another organisation: 404")
check(Fr.post(B + f"/api/obj/{K}/{O1}/trash").status_code == 404, "a person without an organisation: 404")
check(parts(O1) == {"a": None, "b": None, "own": OLD}, f"nothing went before the owner's trash {parts(O1)}")
g0 = len(groups(BOB))
check(Bo.post(B + f"/api/obj/{K}/{O1}/trash").ok, "the owner puts it into the trash")
p = parts(O1)
check(p["a"] and p["b"] and p["own"] == OLD and same_time(O1) == 2, f"its live children went with it (its time), the one before kept its own {p}")
check(Ol.post(B + f"/api/obj/{K}/{O1}/restore").status_code == 404 and Ol.delete(B + f"/api/obj/{K}/{O1}").status_code == 404,
      "another organisation: no restore / delete (404)")
check(Ca.post(B + f"/api/obj/{K}/{O1}/restore").status_code in (403, 404), "a member: no restore")
gs = groups(BOB)
check(len(gs) == g0 + 1 and gs[-1]["label_key"] == "Moved to the trash: {0}" and modes(gs[-1]["id"]) == ["trash"] and gs[-1]["parts"] == 1,
      f"the trash is one step of the person (mode trash, no copy) {gs[-g0 - 1:]}")
GT = gs[-1]["id"]
it = Bo.get(B + "/api/undo").json()["items"]
check(it and it[0]["id"] == GT and it[0]["label"] == "Moved to the trash: Test object" and it[0]["undo"] is True, f"listed in GET /api/undo {it[:1]}")
check(Ol.post(B + f"/api/undo/to/{GT}").status_code == 404, "a foreign step: 404")

# ---- taken back: out of the trash with the children that went with it; redo: into it again
r = Bo.post(B + f"/api/undo/to/{GT}")
check(r.ok and GT in r.json().get("undone", []), f"undo of the trash step {r.status_code} {r.text[:200]}")
check(not dbx("SELECT deleted_at FROM obj_probe WHERE id=?", (O1,))[0][0] and parts(O1) == {"a": None, "b": None, "own": OLD},
      f"out of the trash, the children with it, the own one stays {parts(O1)}")
check(dbx("SELECT state FROM undo_groups WHERE id=?", (GT,))[0][0] == "undone", "the group is undone")
r = Bo.post(B + f"/api/undo/{GT}/redo")
check(r.ok and dbx("SELECT deleted_at FROM obj_probe WHERE id=?", (O1,))[0][0] and same_time(O1) == 2, f"redo: into the trash again {r.text[:200]}")

# ---- a restore is a step too; restored by someone else meanwhile = the trash step stays (409)
check(Bo.post(B + f"/api/obj/{K}/{O1}/restore").ok and parts(O1) == {"a": None, "b": None, "own": OLD}, "restore: the children back")
gs = groups(BOB)
check(gs[-1]["label_key"] == "Restored from the trash: {0}" and modes(gs[-1]["id"]) == ["restore"], f"the restore is a step {gs[-1]}")
check(Bo.post(B + f"/api/obj/{K}/{O1}/trash").ok, "into the trash again")
GT2 = groups(BOB)[-1]["id"]
check(A.post(B + f"/api/obj/{K}/{O1}/restore").ok, "the organisation's admin restores it meanwhile")
r = Bo.post(B + f"/api/undo/to/{GT2}")
st = r.json().get("stayed", []) if r.ok else []
check(r.ok and st and st[0]["code"] == "conflict" and not dbx("SELECT deleted_at FROM obj_probe WHERE id=?", (O1,))[0][0],
      f"undo of a trash someone else took back: the part stays (409), the object stays live {r.status_code} {r.text[:200]}")

# ---------------------------------------------------------------- delete for good
check(Bo.delete(B + f"/api/obj/{K}/{O1}").status_code == 409, "delete for good outside the trash: 409")
check(Bo.post(B + f"/api/obj/{K}/{O1}/trash").ok, "into the trash")
check(Ca.delete(B + f"/api/obj/{K}/{O1}").status_code in (403, 404), "a member: no delete for good")
check(Bo.delete(B + f"/api/obj/{K}/{O1}").ok, "the owner deletes it for good")
check(gone(O1) and parts(O1) == {} and not dbx("SELECT 1 FROM obj_undo WHERE kind=? AND ref_id=?", (K, O1))
      and not dbx("SELECT 1 FROM obj_history WHERE kind=? AND ref_id=?", (K, O1)),
      f"the object, all its children (the own one too), its history and undo steps are gone {parts(O1)}")
check(not dbx("SELECT 1 FROM undo_groups WHERE id IN (?, ?)", (GT, GT2)), "its step groups without parts went (recounted)")

# ---------------------------------------------------------------- a person without an organisation
F1 = with_parts(Fr, "Frida's plan")
check(Bo.post(B + f"/api/obj/{K}/{F1}/trash").status_code == 404, "someone else: 404 on her object")
check(Fr.post(B + f"/api/obj/{K}/{F1}/trash").ok and same_time(F1) == 2, "freelancer: into the trash with the children")
GF = groups(FID)[-1]["id"]
check(Fr.post(B + f"/api/undo/to/{GF}").ok and parts(F1) == {"a": None, "b": None, "own": OLD}, "freelancer: taken back with the children")
check(Fr.post(B + f"/api/obj/{K}/{F1}/trash").ok and Fr.delete(B + f"/api/obj/{K}/{F1}").ok and gone(F1) and parts(F1) == {},
      "freelancer: deleted for good with the children")

# ---------------------------------------------------------------- 2.778.0 (#5371): trash_role 'edit' -- the own trash step goes back
KE = "objprobe_e"  # the second test kind (KALMIDO_TEST_OBJ_PARTS=1): its writers may put it into the trash
for q in ("CREATE TABLE IF NOT EXISTS obj_probe_e (LIKE obj_probe INCLUDING DEFAULTS INCLUDING IDENTITY INCLUDING CONSTRAINTS)",
          "ALTER TABLE obj_probe_e ADD PRIMARY KEY (id)", "GRANT SELECT, INSERT, UPDATE, DELETE ON obj_probe_e TO kalmido_app",
          "GRANT USAGE, SELECT ON SEQUENCE obj_probe_e_id_seq TO kalmido_app"):
    dbx(q)


def e_del(oid):
    return dbx("SELECT deleted_at FROM obj_probe_e WHERE id=?", (oid,))[0][0]


r = Bo.post(B + f"/api/obj/{KE}", json={"title": "Shared plan", "org_id": ORG})
check(r.status_code == 201, f"setup: an object of the edit-trash kind {r.status_code} {r.text[:200]}")
E1 = r.json()["id"]
CARL = uid["carl"]
check(Ca.post(B + f"/api/obj/{KE}/{E1}/trash").ok and e_del(E1), "a member (edit) puts it into the trash (trash_role edit)")
GE = groups(CARL)[-1]["id"]
it = Ca.get(B + "/api/undo").json()["items"]
check(it and it[0]["id"] == GE and it[0]["undo"] is True, f"the member's own trash step is listed {it[:1]}")
check(Ca.post(B + f"/api/obj/{KE}/{E1}/restore").status_code in (403, 404) and e_del(E1),
      "the member: the trash's own restore stays at manage (no restore)")
r = Ca.post(B + f"/api/undo/to/{GE}")
check(r.ok and GE in r.json().get("undone", []) and not r.json().get("stayed") and not e_del(E1),
      f"the member takes the own trash step back: out of the trash {r.status_code} {r.text[:300]}")
r = Ca.post(B + f"/api/undo/{GE}/redo")
check(r.ok and e_del(E1), f"redo: the member puts it into the trash again {r.text[:200]}")
check(Ca.post(B + f"/api/obj/{KE}/{E1}/restore").status_code in (403, 404), "still no restore through the trash for the member")
# someone else's trash meanwhile: the member's old step does not restore what another person put into the trash
check(A.post(B + f"/api/obj/{KE}/{E1}/restore").ok and Bo.post(B + f"/api/obj/{KE}/{E1}/trash").ok, "the admin restores, the owner trashes")
r = Ca.post(B + f"/api/undo/to/{GE}")
check(r.ok and r.json().get("stayed") and e_del(E1), f"the member's old step: another person's trash stays {r.status_code} {r.text[:300]}")
check(Ol.post(B + f"/api/undo/to/{GE}").status_code == 404, "another account: the member's step is not there (404)")

# ---------------------------------------------------------------- the retention run
O2 = with_parts(Bo, "Old plan", ORG)
O3 = with_parts(Bo, "Young plan", ORG)
for o in (O2, O3):
    check(Bo.post(B + f"/api/obj/{K}/{o}/trash").ok, f"into the trash {o}")
dbx("UPDATE obj_probe SET deleted_at=now() - interval '40 days' WHERE id=?", (O2,))
out = in_app(f"""from kalmido.core.writes import obj_trash_due, obj_trash_prune, obj_trash_tick
print("DUE", obj_trash_due(c, "{K}"))
print("DRY", obj_trash_prune(c, "{K}"))
print("TICK", obj_trash_tick(c, force=True))""")
# 2.784.0 (#5366): the tick reports every kind with trash_prune (the office's suppliers too) - this kind's count is the one asked
check(f"DUE [{O2}]" in out and "DRY 1" in out and "TICK {" in out and f"'{K}': 1" in out.split("TICK", 1)[-1], f"due: only the old one; switch off = counted {out[-400:]}")
check(not gone(O2) and not gone(O3), "switch off: nothing deleted")
last = dbx("SELECT value FROM settings WHERE key='ret_last_trash.obj_trash'")
# 2.809.0 (#5365): file-store nodes, knowledge pages and tables report in the same run (only kinds with a count are kept)
check(last and json.loads(last[0][0]).get("counts", {}).get(K) == 1 and json.loads(last[0][0]).get("purged") is False, f"reported for the retention page {last}")
out = in_app(f"""from kalmido.core.writes import obj_trash_prune
print("PURGED", obj_trash_prune(c, "{K}", purge=True))
c.commit()""")
check("PURGED 1" in out and gone(O2) and parts(O2) == {} and not gone(O3) and len(parts(O3)) == 3,
      f"switch on: the old one with its children gone, the young one stays {out[-300:]}")

# ---- the calendars' run goes the same core way
# 2.925.0 (#5367): ev_cal_trash_purge is gone - the calendars are a trash_prune kind of the core's run itself
out = in_app("""from kalmido.core.objects import OBJ
from kalmido.core.writes import obj_trash_prune
print("CAL", obj_trash_prune(c, "evcal", "2000-01-01T00:00:00+00:00", False), OBJ["evcal"]["trash_prune"])""")
check("CAL 0 True" in out, f"the calendars' retention run answers through the core {out[-300:]}")

# ---------------------------------------------------------------- live_sql / trash_sql
out = in_app("""from kalmido.core.access import live_sql, trash_sql, otr_live
print("L", live_sql(), "|", live_sql("t"), "|", trash_sql("t", "revoked_at"), "|", otr_live())
for a in (("t; drop", "deleted_at"), ("t", "name")):
    try:
        live_sql(*a)
        print("NOERR", a)
    except ValueError:
        print("ERR")""")
check("L deleted_at IS NULL | t.deleted_at IS NULL | t.revoked_at IS NOT NULL | l.deleted_at IS NULL" in out and out.count("ERR") == 2
      and "NOERR" not in out, f"live_sql / trash_sql: the condition, a wrong alias / column is refused {out[-300:]}")

sys.exit(done("p2773_b_trash_core"))
