// 2.905.0 / 2.905.0 (#5288, stage Q10): section templates after their move onto the shared core, in the app.
// kalmido-suite: fresh
// Section templates of a database from before (table section_templates) are templates of the shared core after the next start (core/tplmove.py) and look and work the same in the app: the dialog of a project ("Section
// templates…") lists them with their name and their sections, "Add" puts the missing sections into the project (they show as its
// sections, the dialog closes), and an organisation's template shows for a member too. Desktop (mouse) and phone (finger).
// 2.905.0: a new one saved from a project is listed with its sections and used on another project; deleted it is gone from the
// dialog, the trash view names it, "Restore" brings it back and the dialog shows it with its sections again.
// Invented names only. P2905CUI_NOSTART=1 = the container is running (then the move part is skipped: it needs a restart).
const path = require('path');
const {execFileSync} = require('child_process');
const {sleep, B, login} = require('./boot');
const F = []; let ok = 0;
const check = (c, what) => { if (c) ok++; else { F.push(what); console.log('FAIL:', what); } };
const firefox = require('./ff')({tag: 'p2905_c_tplkind_ui', check, shots: 'P2905CUI_SHOTS'});
const H = {'Content-Type': 'application/json', 'X-Requested-With': 'kalmido'};
const DATA = process.argv[2] || path.join(__dirname, '.data');
const NOSTART = process.env.P2905CUI_NOSTART === '1';
const start = keep => execFileSync('bash', [path.join(__dirname, 'start.sh'), DATA], {stdio: 'ignore', env: {...process.env, ...(keep ? {KEEP: '1'} : {})}});
const call = async (ck, method, url, body) => { const r = await fetch(B + url.replace(/^\//, ''), {method, headers: {...H, Cookie: ck}, body: body ? JSON.stringify(body) : undefined}); const j = await r.json().catch(() => ({})); return Object.assign(j, {http: r.status}); };
// SQL on the suite's database (tests/dbx.py, as the Python suites): the table as a version before 2.905 had it
const sql = (q, args = []) => execFileSync('python3', [path.join(__dirname, 'dbx.py'), DATA, q, JSON.stringify(args)], {encoding: 'utf8'});
const health = async () => { for (let i = 0; i < 120; i++) { try { if ((await fetch(B + 'api/health')).ok) return true; } catch { /* starting */ } await sleep(500); } return false; };

(async () => {
  if (!NOSTART) start(false);
  await health();
  const r = await fetch(B + 'api/auth/setup', {method: 'POST', headers: H, body: JSON.stringify({username: 'alice', display_name: 'Alice', password: 'password123', wizard: true, lang: 'en'})});
  check(r.ok, 'setup');
  let CA = await login('alice');
  await call(CA, 'POST', '/api/admin/setup', {org_name: 'Alpha Example', lang: 'en', collab_all: true, modules: ['comments']});
  const st0 = await call(CA, 'GET', '/api/state');
  const ORG = st0.me.workspaces[0].id, ALICE = st0.me.id;
  const bob = await call(CA, 'POST', '/api/users', {orgs: [{id: ORG, role: 'member'}], username: 'bob', display_name: 'Bob', password: 'password123', email: 'bob@example.com'});
  check(bob.http < 300, 'setup: bob as a member');
  for (const ck of [CA, await login('bob')]) await call(ck, 'PATCH', '/api/settings', {lang: 'en', tour: 'done'});
  const L = await call(CA, 'POST', '/api/lists', {name: 'Spring shoot', org_id: ORG});
  await call(CA, 'POST', '/api/sections', {list_id: L.id, name: 'Shoot'});
  const LB = await call(await login('bob'), 'POST', '/api/lists', {name: 'Bob notes'});

  if (!NOSTART) {  // the section templates as a version before 2.905 kept them, then the next start moves them
    sql(`CREATE TABLE section_templates (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id)
         ON DELETE CASCADE, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE, name TEXT NOT NULL, sections TEXT NOT NULL DEFAULT '[]',
         created_at TEXT NOT NULL, updated_at TEXT NOT NULL)`);
    sql('INSERT INTO section_templates(user_id, org_id, name, sections, created_at, updated_at) VALUES(?,?,?,?,?,?)',
      [ALICE, ORG, 'Film workflow', JSON.stringify(['Prep', 'Shoot', 'Edit']), '2026-10-01T08:00:00+00:00', '2026-10-01T08:00:00+00:00']);
    sql('INSERT INTO section_templates(user_id, org_id, name, sections, created_at, updated_at) VALUES(?,?,?,?,?,?)',
      [ALICE, null, 'My week', JSON.stringify(['Monday', 'Friday']), '2026-10-01T08:00:00+00:00', '2026-10-01T08:00:00+00:00']);
    start(true);
    check(await health(), 'the app starts again on the old table');
    CA = await login('alice');
  } else {
    await call(CA, 'POST', '/api/section-templates', {name: 'Film workflow', sections: ['Prep', 'Shoot', 'Edit'], space: 'org:' + ORG});
    await call(CA, 'POST', '/api/section-templates', {name: 'My week', sections: ['Monday', 'Friday']});
  }
  const ts = (await call(CA, 'GET', '/api/section-templates')).templates || [];
  check(ts.map(t => t.name).sort().join() === 'Film workflow,My week', 'API: both templates after the move ' + ts.map(t => t.name));

  const ready = async (ev, expr, n = 60) => { for (let i = 0; i < n; i++) { if (await ev(expr).catch(() => false)) return true; await sleep(250); } return false; };
  const signIn = (ev, u) => ev(`fetch('/api/auth/login', {method: 'POST', headers: {'Content-Type': 'application/json', 'X-Requested-With': 'kalmido'}, body: JSON.stringify({username: '${u}', password: 'password123'})}).then(r => r.ok)`);
  const secs = lid => `S.sections.filter(s => s.list_id === ${lid}).sort((a, b) => a.sort - b.sort || a.id - b.id).map(s => s.name).join()`;
  // the dialog's row of a template by its name (the text a person reads)
  const row = name => `[...document.querySelectorAll('.sctmodal .sctt')].find(x => x.querySelector('.n')?.textContent.includes(${JSON.stringify(name)}))`;

  await firefox(async ({cmd, ev, ctx, nav, shot}) => {
    await cmd('browsingContext.setViewport', {context: ctx, viewport: {width: 1280, height: 900}});
    await nav(B + 'static/icon.svg');
    await ev(`(() => { localStorage.clear(); sessionStorage.clear(); localStorage.setItem('tasks.theme', '"light"'); return 1; })()`);
    await signIn(ev, 'alice');
    await nav(B + '#l/' + L.id);
    check(await ready(ev, `${secs(L.id)} === 'Shoot'`), 'desktop: the project with its one section');
    // in: the project menu's entry opens the dialog (list menu item, dialogs.js listMenuItems -> sct_open)
    await ev(`(() => { sct_open(${L.id}); return 1; })()`);
    check(await ready(ev, `!!(${row('Film workflow')})`), 'desktop: the moved template is listed by its name');
    const txt = await ev(`(${row('Film workflow')})?.textContent || ''`);
    check(/Prep/.test(txt) && /Shoot/.test(txt) && /Edit/.test(txt), 'desktop: with its sections in their order: ' + txt.slice(0, 120));
    check(await ev(`!!(${row('My week')})`), 'desktop: the private one too');
    check(await ev(`!!(${row('Film workflow')})?.querySelector('[data-m="del"]')`), 'desktop: the admin may delete it (bin shown)');
    await shot('p2905-c-sectpl-desktop.png');
    // use it: only the missing sections are added, the dialog closes, the project shows them
    await ev(`(() => { (${row('Film workflow')}).querySelector('[data-m="apply"]').click(); return 1; })()`);
    check(await ready(ev, `${secs(L.id)} === 'Shoot,Prep,Edit'`), 'desktop: Add put the missing sections at the end');
    check(await ready(ev, `!document.querySelector('.sctmodal')`), 'desktop: back in the project (the dialog closed)');
    check(await ready(ev, `[...document.querySelectorAll('#view .ghead')].map(x => x.textContent).join(' ').includes('Edit')`), 'desktop: the new section shows in the project');
  }, false);

  await firefox(async ({cmd, ev, ctx, nav, shot}) => {
    await cmd('browsingContext.setViewport', {context: ctx, viewport: {width: 390, height: 844}});
    await nav(B + 'static/icon.svg');
    await ev(`(() => { localStorage.clear(); sessionStorage.clear(); localStorage.setItem('tasks.theme', '"light"'); return 1; })()`);
    await signIn(ev, 'bob');
    await nav(B + '#l/' + LB.id);
    check(await ready(ev, `!!listById(${LB.id}) && !!document.querySelector('#view')`), 'phone: bob\'s project');
    await ev(`(() => { sct_open(${LB.id}); return 1; })()`);
    check(await ready(ev, `!!(${row('Film workflow')})`), 'phone: a member sees the organisation\'s template by its name');
    check(await ev(`!(${row('My week')})`), 'phone: not alice\'s private one');
    check(await ev(`!(${row('Film workflow')})?.querySelector('[data-m="del"]')`), 'phone: a member cannot delete it (no bin)');
    check(await ev(`(() => { const b = (${row('Film workflow')}).querySelector('[data-m="apply"]').getBoundingClientRect(); return b.width > 0 && b.right <= innerWidth && b.bottom <= innerHeight; })()`),
      'phone: its Add button is on the screen');
    await shot('p2905-c-sectpl-phone.png');
    await ev(`(() => { (${row('Film workflow')}).querySelector('[data-m="apply"]').click(); return 1; })()`);
    check(await ready(ev, `${secs(LB.id)} === 'Prep,Shoot,Edit'`), 'phone: the sections added to bob\'s project');
    check(await ready(ev, `!document.querySelector('.sctmodal')`), 'phone: back in the project');
  }, true);

  // 2.905.0 (#5288): save -> listed -> use -> delete -> the trash -> restore (its sections visible again)
  CA = await login('alice');
  const L2 = await call(CA, 'POST', '/api/lists', {name: 'Autumn shoot', org_id: ORG});
  await firefox(async ({cmd, ev, ctx, nav, shot}) => {
    await cmd('browsingContext.setViewport', {context: ctx, viewport: {width: 1280, height: 900}});
    await nav(B + 'static/icon.svg');
    await ev(`(() => { localStorage.clear(); sessionStorage.clear(); localStorage.setItem('tasks.theme', '"light"'); return 1; })()`);
    await signIn(ev, 'alice');
    await nav(B + '#l/' + L.id);
    check(await ready(ev, `${secs(L.id)} === 'Shoot,Prep,Edit'`), 'new: the project with its three sections');
    await ev(`(() => { sct_open(${L.id}); return 1; })()`);
    check(await ready(ev, `!!document.querySelector('.sctmodal #sct-name') && !!(${row('Film workflow')})`), 'new: the dialog offers to save the sections');
    await ev(`(() => { document.querySelector('.sctmodal #sct-name').value = 'Season plan'; document.querySelector('.sctmodal [data-m="save"]').click(); return 1; })()`);
    check(await ready(ev, `/Shoot.*Prep.*Edit/.test((${row('Season plan')})?.textContent || '')`), 'new: the saved template is listed with its sections in their order');
    await ev(`(() => { document.querySelector('.sctmodal [data-m="close"]').click(); return 1; })()`);
    await nav(B + '#l/' + L2.id);
    check(await ready(ev, `!!listById(${L2.id}) && ${secs(L2.id)} === ''`), 'new: the other project without sections');
    await ev(`(() => { sct_open(${L2.id}); return 1; })()`);
    check(await ready(ev, `!!(${row('Season plan')})`), 'new: listed in the other project\'s dialog');
    await ev(`(() => { (${row('Season plan')}).querySelector('[data-m="apply"]').click(); return 1; })()`);
    check(await ready(ev, `${secs(L2.id)} === 'Shoot,Prep,Edit'`), 'new: used -- the other project has its sections');
    check(await ready(ev, `[...document.querySelectorAll('#view .ghead')].map(x => x.textContent).join(' ').includes('Prep')`), 'new: they show in the project');
    // delete it: asked, gone from the dialog
    await ev(`(() => { sct_open(${L2.id}); return 1; })()`);
    check(await ready(ev, `!!(${row('Season plan')})?.querySelector('[data-m="del"]')`), 'trash: the admin sees its bin');
    await ev(`(() => { (${row('Season plan')}).querySelector('[data-m="del"]').click(); return 1; })()`);
    check(await ready(ev, `!!document.querySelector('.cdlg [data-cd="yes"]')`), 'trash: the delete asks first');
    await ev(`(() => { document.querySelector('.cdlg [data-cd="yes"]').click(); return 1; })()`);
    check(await ready(ev, `!!document.querySelector('.sctmodal') && !(${row('Season plan')}) && !!(${row('Film workflow')})`), 'trash: gone from the dialog, the others stay');
    await ev(`(() => { document.querySelector('.sctmodal [data-m="close"]').click(); return 1; })()`);
    // the trash view names it; Restore brings it back
    const trow = `[...document.querySelectorAll('.ptrlist [data-ptr]')].find(x => x.textContent.includes('Season plan'))`;
    await ev(`(() => { location.hash = '#trash'; return 1; })()`);
    check(await ready(ev, `S.route.key === 'trash' && !!(${trow})`, 80), 'trash: the trash view names the deleted template');
    await shot('p2905-c-sectpl-trash.png');
    await ev(`(() => { (${trow}).querySelector('[data-ptra="restore"]').click(); return 1; })()`);
    check(await ready(ev, `!(${trow})`), 'trash: Restore takes it out of the trash view');
    await nav(B + '#l/' + L.id);
    check(await ready(ev, `${secs(L.id)} === 'Shoot,Prep,Edit'`), 'back: the project again');
    await ev(`(() => { sct_open(${L.id}); return 1; })()`);
    check(await ready(ev, `/Shoot.*Prep.*Edit/.test((${row('Season plan')})?.textContent || '')`), 'back: the dialog lists it again with its sections');
  }, false);

  console.log(`p2905_c_tplkind_ui: ${ok} ok, ${F.length} failed`);
  process.exit(F.length ? 1 : 0);
})().catch(e => { console.log('FAIL:', e.stack || e); console.log(`p2905_c_tplkind_ui: ${ok} ok, ${F.length + 1} failed`); process.exit(1); });
