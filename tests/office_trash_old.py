"""2.1073.0 (#5865): the table office_trash is gone -- schema.py no longer creates it, and every start of the app (also a
suite's helper that loads it: obj_probe.in_app, orgcrypt_cli) writes its copies back (office/okern.py ofk_copies_back) and
then drops it (ofk_trash_drop). A suite that plays the copies of an older database makes the table as the versions before
2.1073 did (OLD_DDL) right before it files a copy; the next start of the app takes them back and drops it again.
GONE: the query that is true while the table is not there."""

OLD_DDL = ("CREATE TABLE IF NOT EXISTS office_trash (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
           "org_id BIGINT NOT NULL REFERENCES orgs(id) ON DELETE CASCADE, kind TEXT NOT NULL, sub TEXT NOT NULL DEFAULT '', "
           "ref_id BIGINT NOT NULL, label TEXT NOT NULL DEFAULT '', snap TEXT NOT NULL DEFAULT '{}', "
           "deleted_by BIGINT REFERENCES users(id) ON DELETE SET NULL, deleted_at TEXT NOT NULL)")
GONE = "SELECT to_regclass('office_trash') IS NULL"
# the lines kalmido/startup.py prints (the copies' run, then the drop)
BACK_LINE = "office trash: copies back into their tables"
DROP_LINE = "office trash: the old table office_trash is gone ("


def gone(q):
    """True when the table is not there; q = the suite's query function (dbx / sql / one style: rows or a value)."""
    r = q(GONE)
    v = (r[0][0] if r else None) if isinstance(r, list) else r
    return v in (True, 1, "t", "true", "True")


def dropped(out):
    """The number of copies the start dropped with the table (from its log line), None when it dropped nothing."""
    for line in str(out or "").splitlines():
        if line.startswith(DROP_LINE):
            try:
                return int(line[len(DROP_LINE):].split()[0])
            except (ValueError, IndexError):
                return None
    return None
