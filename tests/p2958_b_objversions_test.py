"""2.958.0 part B (#5281, stage Q7a of the cross-cutting core): obj_versions is the core's second table, the versions of the
knowledge pages live there, wiki_versions is gone. Own container (mode workspaces). Invented names only.
tenant-matrix: wiki
freelancer-matrix: wiki
 - a new database: no wiki_versions, obj_versions with real types; saves of a page write numbered rows (kind wiki), the
   version list / one version / restore answer as before (+ the number), another organisation 404
 - the move at the start (wiki/wkhist.py wkh_retire): an old wiki_versions (as 2.123 - 2.957 made it) with a plain row, a row
   sealed with the old context, a row held at a lock and a private row of a person without an organisation -> each in
   obj_versions with its id, the next numbers of its page, held_at, the sealed text readable (sealed again at rest); a row
   whose text cannot be opened keeps the table (start check, log line), nothing dropped
 - once that row is gone: the next start drops wiki_versions (log line), the back limit names #5281, a later start is a
   no-op; a new save after the move gets a new id and the next number
 - a page deleted for good takes its versions along (trigger kalmido_ov_gone)
usage: p2958_b_objversions_test.py <datadir>"""
