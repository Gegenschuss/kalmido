FEAT = "cal,comments,collab,wiki"
CT = os.environ.get("KALMIDO_TEST_CONTAINER", "kalmido-test")
OLD_DDL = ("CREATE TABLE IF NOT EXISTS wiki_versions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
           "page_id BIGINT NOT NULL REFERENCES wiki_pages(id) ON DELETE CASCADE, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE, "
           "owner_id BIGINT REFERENCES users(id) ON DELETE CASCADE, path TEXT NOT NULL DEFAULT '', body TEXT NOT NULL DEFAULT '', "
           "size BIGINT NOT NULL DEFAULT 0, created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, created_at TEXT NOT NULL, "
           "updated_at TEXT NOT NULL, wkx_held_at TEXT)")  # the table as 2.123 - 2.957 made it (+ 4306_d's column)
OLD_INS = ("INSERT INTO wiki_versions(id,page_id,org_id,owner_id,path,body,size,created_by,created_at,updated_at,wkx_held_at) "
           "VALUES(?,?,?,?,?,?,?,?,?,?,?)")
LABEL = "knowledge history, stage Q7a (#5281)"

kt.fresh(env={"KALMIDO_INSTANCE_MODE": "workspaces", "KALMIDO_ORGCRYPT_DELAY": "0",
              "KALMIDO_SECRET_KEY": base64.b64encode(os.urandom(32)).decode()}, prefix="P2958B")  # a server key: sealed versions


def sql(q, args=(), write=False):
    c = dbxm.connect(os.path.join(DATA, "tasks.db"), timeout=10)
    try:
        r = c.execute(q, args)
        if write:
            c.commit()
            return None
        return r.fetchall()
    finally:
        c.close()


def logs():
    r = subprocess.run(["docker", "logs", CT], capture_output=True, text=True)
    return r.stdout + r.stderr


def _health():
    try:
        return requests.get(B + "/api/health", timeout=3).ok
    except requests.RequestException:
        return False


def restart():
    """The next start of the server (core/db.py init_db runs the START hooks: wkhist.wkh_retire)."""
    subprocess.run(["docker", "restart", CT], capture_output=True)
    check(until(lambda: _health(), timeout=90), "the server is up again after the restart")


def in_app(code, *args):
    r = subprocess.run(["docker", "exec", "-i", "-e", "TASKS_WATCHDOG=0", CT, "python", "-c", code, *map(str, args)],
                       capture_output=True, text=True)
    try:
        return json.loads(r.stdout.strip().splitlines()[-1])
    except (ValueError, IndexError):
        return {"error": (r.stdout + r.stderr)[-600:]}


def old_table():
    return sql("SELECT to_regclass('wiki_versions')")[0][0] is not None


def vrows(pid):
    return sql("SELECT id, no, title, held_at FROM obj_versions WHERE kind='wiki' AND ref_id=? ORDER BY id", (pid,))


def page(s, space, path, body=""):
    r = s.post(B + "/api/wiki/pages", json={"space": space, "path": path, "body": body})
    check(r.status_code == 201, f"setup: page {path} {r.text[:160]}")
    return r.json()["id"]


def save(s, pid, text):
    r = s.patch(B + f"/api/wiki/pages/{pid}", json={"body": text})
    check(r.ok, f"setup: save {pid} {r.status_code} {r.text[:160]}")


def vlist(s, pid):
    r = s.get(B + f"/api/wiki/pages/{pid}/versions")
    return r.json().get("versions") if r.ok else None


A = kt.setup()
A.patch(B + "/api/settings", json={"lang": "en", "features": FEAT, "tour": "done"})
ALICE = A.get(B + "/api/me").json()["id"]
r = A.post(B + "/api/users", json={"username": "bob", "display_name": "Bob", "password": "password123", "email": "bob@example.com", "orgs": []})
assert r.ok, r.text
BOB = r.json()["id"]
Bo = sess("bob")
Bo.patch(B + "/api/settings", json={"lang": "en", "features": FEAT, "tour": "done"})
r = A.post(B + "/api/admin/orgs", json={"name": "Lambda"})
assert r.status_code in (200, 201), r.text
K = r.json()["id"]
sql("INSERT INTO org_members(org_id,user_id,role) VALUES(?,?,'admin') ON CONFLICT (org_id,user_id) DO UPDATE SET role='admin'", (K, ALICE), write=True)
check(A.put(B + f"/api/orgs/{K}/members", json={"email": "bob@example.com", "role": "member"}).ok, "setup: bob is a member of Lambda")
r = A.post(B + "/api/admin/orgs", json={"name": "Other"})
K2 = r.json()["id"]
FE, Fe = freelancer(B, A, "fred", features=FEAT)
r = A.post(B + "/api/users", json={"username": "olga", "display_name": "Olga", "password": "password123", "email": "olga@example.com", "orgs": []})
OLGA = r.json()["id"]
Ol = sess("olga")
check(A.put(B + f"/api/orgs/{K2}/members", json={"email": "olga@example.com", "role": "member"}).ok, "setup: olga is in another organisation")
SP = f"org:{K}"

# ================================================================== a new database: the core's versions
check(not old_table(), "a new database has no wiki_versions")
types = dict(sql("SELECT column_name, data_type FROM information_schema.columns WHERE table_name='obj_versions'"))
check(types.get("created_at") == "timestamp with time zone" and types.get("held_at") == "timestamp with time zone"
      and types.get("no") == "bigint", f"obj_versions has real types {types}")
P = page(A, SP, "Handbuch/Start", "eins")
save(A, P, "eins zwei")
save(Bo, P, "eins zwei drei")  # another person: a version of its own
vr = vrows(P)
check([x[1] for x in vr] == [1, 2] and all(x[2] == "Handbuch/Start" for x in vr), f"saves write numbered rows of kind wiki {vr}")
vs = vlist(Bo, P)
check(vs is not None and [v["no"] for v in vs] == [2, 1] and vs[0]["current"] and vs[0]["by_name"] == "Bob"
      and vs[1]["path"] == "Handbuch/Start", f"the version list as before, newest first, + the number {vs}")
one = Bo.get(B + f"/api/wiki/pages/{P}/versions/{vs[1]['id']}").json()
check(one.get("body") == "eins zwei" and one.get("no") == 1, f"one version with its text {one}")
cur = A.get(B + f"/api/wiki/pages/{P}").json()
r = A.post(B + f"/api/wiki/pages/{P}/versions/{vs[1]['id']}/restore", json={"expect_updated_at": cur["updated_at"]})
check(r.ok and r.json().get("body") == "eins zwei" and r.json().get("restored") == vs[1]["id"], f"restore {r.text[:200]}")
check([x[1] for x in vrows(P)] == [1, 2, 3], f"the restore is version 3 on top {vrows(P)}")
r = A.post(B + f"/api/wiki/pages/{P}/versions/{vs[1]['id']}/restore", json={"expect_updated_at": "2000-01-01T00:00:00+00:00"})
check(r.status_code == 409, f"restore with an old expect_updated_at: 409 ({r.status_code})")
check(Ol.get(B + f"/api/wiki/pages/{P}/versions").status_code == 404 and Ol.get(B + f"/api/wiki/pages/{P}/versions/{vs[0]['id']}").status_code == 404
      and Ol.post(B + f"/api/wiki/pages/{P}/versions/{vs[0]['id']}/restore", json={}).status_code == 404, "another organisation: 404")
FP = page(Fe, "private", "Tagebuch", "a")
save(Fe, FP, "a b")
fv = vlist(Fe, FP)
check(fv and fv[0]["no"] == 1 and fv[0]["current"], f"freelancer: the private page has its numbered version {fv}")
check(Ol.get(B + f"/api/wiki/pages/{FP}/versions").status_code == 404, "freelancer: nobody else reads her history")

# ================================================================== the move at the start: one row cannot be opened
SEAL = in_app("import app, json, sys\nfrom kalmido.core.db import connect\nfrom kalmido.core.pg import system_ctx\n"
              "from kalmido.core.orgcrypt import oc_key\nfrom kalmido.wiki.wkhist import _seal, WKH_OLD_VCTX\n"
              "c = connect()\nwith system_ctx(c):\n    k = oc_key(c, int(sys.argv[1]))\n"
              "    print(json.dumps(_seal(k, int(sys.argv[1]), WKH_OLD_VCTX, 'Alter versiegelter Stand') if k else None))\nc.commit()\nc.close()", K)
check(isinstance(SEAL, str) and SEAL.startswith("kenc1:"), f"setup: a text sealed with the old context {str(SEAL)[:80]}")
sql(OLD_DDL, write=True)
T0, T1 = "2026-03-01T10:00:00.000+00:00", "2026-03-02T10:00:00.000+00:00"
HELD = "2026-03-03T10:00:00+00:00"
old = [(900001, P, K, None, "Handbuch/Alt", "Alter Klartext", 14, ALICE, T0, T0, None),
       (900002, P, K, None, "Handbuch/Alt", SEAL, 24, BOB, T1, T1, None),
       (900003, P, K, None, "Handbuch/Alt", "Gehaltener Stand", 16, ALICE, T1, T1, HELD),
       (900004, FP, None, FE, "Tagebuch", "Alter privater Stand", 20, FE, T0, T0, None),
       (900005, P, K, None, "Handbuch/Alt", "kenc1:" + "A" * 48, 9, ALICE, T1, T1, None)]  # cannot be opened (no valid tag)
for x in old:
    sql(OLD_INS, x, write=True)
restart()
A, Bo, Fe = sess("alice"), sess("bob"), sess("fred")
check(old_table(), "start check: a row that cannot be opened keeps wiki_versions (nothing dropped)")
check(f"{LABEL}: 1 old row(s) of wiki_versions cannot be opened now" in logs(), "start check: the log names the row left")
check(sql("SELECT id FROM wiki_versions") == [(900005,)], f"start check: only that row stays {sql('SELECT id FROM wiki_versions')}")
mv = {x[0]: x for x in vrows(P)}
check({900001, 900002, 900003} <= set(mv) and [mv[i][1] for i in (900001, 900002, 900003)] == [4, 5, 6],
      f"moved with their ids and the next numbers of the page {sorted(mv.values())}")
check(mv[900003][3] and not mv[900001][3], f"wkx_held_at became held_at {mv[900003]}")
body = sql("SELECT body FROM obj_versions WHERE id=900002")[0][0]
check(body.startswith("kenc1:") and body != SEAL, "the sealed text is sealed again at rest (the new context)")
r = Bo.get(B + f"/api/wiki/pages/{P}/versions/900002")
check(r.ok and r.json().get("body") == "Alter versiegelter Stand" and r.json().get("path") == "Handbuch/Alt", f"and reads as before {r.text[:200]}")
ids = [v["id"] for v in vlist(Bo, P) or []]
check(900001 in ids and 900002 in ids and 900003 not in ids, f"the list shows the moved rows, the held one stays hidden {ids}")
check(Bo.get(B + f"/api/wiki/pages/{P}/versions/900003").status_code == 404, "the held version: 404 (nobody named for its hold)")
fv = vlist(Fe, FP) or []
check(any(v["id"] == 900004 for v in fv) and Fe.get(B + f"/api/wiki/pages/{FP}/versions/900004").json().get("body") == "Alter privater Stand",
      f"freelancer: her private old version moved and reads {fv}")
cur = A.get(B + f"/api/wiki/pages/{P}").json()
r = A.post(B + f"/api/wiki/pages/{P}/versions/900001/restore", json={"expect_updated_at": cur["updated_at"]})
check(r.ok and r.json().get("body") == "Alter Klartext", f"a moved version restores {r.text[:200]}")

