#!/usr/bin/env python3
# kalmido-suite: after=p2501_a_nosham nodata
"""2.771.0 (#5333): tools/check_migrations.py flags a column DEFAULT whose function call the backup restore refuses
(kalmido/admin/backup.py _CALL_HEADS). Static, no container.
 - DEFAULT now() in a SCHEMA table, a MIGRATIONS step and an AFTER column: a finding that names now() and CURRENT_TIMESTAMP
 - CURRENT_TIMESTAMP, a constant, a cast, COALESCE / lower (in the list), GENERATED BY DEFAULT AS IDENTITY, a REFERENCES x(id)
   after the DEFAULT, now() inside a function body ($$...$$) and in a comment: no finding
 - the list is the one of backup.py (read from there), and the fragments of the repository pass
usage: check_migrations_default_test.py"""
import os
import sys

from kt import FAILS, OKS, check

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "tools"))
import check_migrations as cm  # noqa: E402

T = "CREATE TABLE IF NOT EXISTS t1 (\n  id BIGSERIAL PRIMARY KEY,\n  {col}\n);"


def schema(col):
    return cm.content_findings("x.py", {"SCHEMA": (T.format(col=col), 3)}, "")


out = schema("created_at TIMESTAMPTZ NOT NULL DEFAULT now()")
check(out and "now()" in out[0] and "CURRENT_TIMESTAMP" in out[0], f"DEFAULT now() in a SCHEMA table is a finding: {out}")
out = cm.content_findings("x.py", {"MIGRATIONS": ([("t1", "at", "ALTER TABLE t1 ADD COLUMN at TIMESTAMPTZ DEFAULT now()")], 5)}, "")
check(out and "step t1.at" in out[0] and "now()" in out[0], f"DEFAULT now() in a step is a finding: {out}")
out = cm.content_findings("x.py", {"AFTER": (["ALTER TABLE t1 ADD COLUMN IF NOT EXISTS u TEXT DEFAULT gen_random_uuid()::text"], 7)}, "")
check(out and "gen_random_uuid()" in out[0], f"another unknown call in an AFTER column is a finding: {out}")
for ok in ("created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP", "n INTEGER NOT NULL DEFAULT 0",
           "kind TEXT DEFAULT 'a'::text CHECK (kind IN ('a', 'b'))", "x TEXT DEFAULT lower('A')", "y TEXT DEFAULT COALESCE(NULL, 'b')",
           "row_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE", "o BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL",
           "z NUMERIC(10,2) DEFAULT 0, w TEXT  -- DEFAULT now() is not allowed"):
    check(schema(ok) == [], f"no finding: {ok} {schema(ok)}")
FN = "CREATE OR REPLACE FUNCTION f1() RETURNS trigger AS $$ BEGIN NEW.x := DEFAULT now(); RETURN NEW; END $$ LANGUAGE plpgsql"
check(cm.default_call_finding(FN) is None, "now() inside a function body is no column DEFAULT")
check("now" not in {h.lower() for h in cm.call_heads()} and "COALESCE" in cm.call_heads(), "the heads come from backup.py")
check(cm.findings() == [], f"the fragments of the repository pass {cm.findings()[:3]}")

print(f"check_migrations_default: {OKS[0]} ok, {len(FAILS)} failed")
sys.exit(1 if FAILS else 0)
