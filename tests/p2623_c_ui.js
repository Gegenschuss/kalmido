// 2.623.0 UI test of part C (#4718: an agent's change of a core object as a proposal, kind obj_patch; static/js/objprop.js).
// kalmido-suite: fresh
// Own container (start.sh with the test kind objprobe, KALMIDO_TEST_OBJ=1, as tests/obj_probe.py). Invented names only. jsdom:
// - the card: who proposes it, the object, per field the value now -> the proposed one, 👍 Accept / 👎 Decline, no entry list
// - 👍 writes the value as the person (server), the toast names the fields
// - changed by someone else while the card is open: Accept answers 409, the card shows the plain message, nothing written
// - opened after such a change: the card says so and Accept is off
// Firefox (real layout, skipped without firefox): 390 px - the card stays inside the screen (screenshot)
const {execFileSync} = require('child_process');
const path = require('path');
const {boot, sleep, B, login} = require('./boot');
const firefox = require('./ff')({tag: 'p2623_c_ui', check: (c, w) => check(c, w), shots: 'P2623C_SHOTS'});
const F = []; let ok = 0;
const check = (c, what) => { if (c) ok++; else { F.push(what); console.log('FAIL:', what); } };
const H = {'Content-Type': 'application/json', 'X-Requested-With': 'kalmido'};
const DATA = process.argv[2] || path.join(__dirname, '.data');
if (!process.env.P2623C_NOSTART) execFileSync('bash', [path.join(__dirname, 'start.sh'), DATA], {stdio: 'ignore', env: {...process.env, EXTRA: ((process.env.EXTRA || '') + ' -e KALMIDO_TEST_OBJ=1').trim()}});
let CK;
const call = async (method, url, body, ck = CK, hd = {}) => { const r = await fetch(B + url.replace(/^\//, ''), {method, headers: {...H, ...(ck ? {Cookie: ck} : {}), ...hd}, body: body ? JSON.stringify(body) : undefined}); return {...(await r.json().catch(() => ({}))), http: r.status}; };
const until = (fn, n) => require('./boot').until(fn, {timeout: n ? n * 150 : 15000, step: 150});
const click = (w, el) => el && el.dispatchEvent(new w.MouseEvent('click', {bubbles: true, cancelable: true}));
const sql = (q, a = []) => JSON.parse(execFileSync('python3', [path.join(__dirname, 'dbx.py'), DATA, q, JSON.stringify(a)]).toString() || '[]');
const K = 'objprobe';

(async () => {
  await sleep(600);
  sql(`CREATE TABLE IF NOT EXISTS obj_probe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, rev BIGINT NOT NULL DEFAULT 1, created_at TEXT NOT NULL,
    created_by BIGINT, updated_at TEXT NOT NULL, updated_by BIGINT, deleted_at TEXT, deleted_by BIGINT,
    title TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '', size BIGINT, done BIGINT NOT NULL DEFAULT 0)`);
  sql('GRANT SELECT, INSERT, UPDATE, DELETE ON obj_probe TO kalmido_app');
  sql('GRANT USAGE, SELECT ON SEQUENCE obj_probe_id_seq TO kalmido_app');
  await fetch(B + 'api/auth/setup', {method: 'POST', headers: H, body: JSON.stringify({username: 'alice', display_name: 'Alice', password: 'password123'})});
  CK = await login('alice');
  await call('POST', '/api/admin/setup', {lang: 'en', collab_all: true});
  await call('PATCH', '/api/settings', {lang: 'en', tour: 'done'});
  await call('PUT', '/api/admin/agent-policy', {user_agents: true});
  const ag = await call('POST', '/api/my/agents', {username: 'claude', display_name: 'Claude', scopes: ['read', 'comments']});
  check(ag.http < 300 && ag.token, 'setup: her agent ' + ag.http + JSON.stringify(ag.error || ''));
  const AGH = {Authorization: 'Bearer ' + ag.token};
  const o = await call('POST', `/api/obj/${K}`, {title: 'Kick-off', note: 'first draft', size: 2});
  check(o.http === 201, 'setup: an object ' + o.http);
  check((await call('POST', `/api/obj/${K}/${o.id}/shares`, {agent_id: ag.id, role: 'view'})).http === 201, 'setup: shared with the agent (view)');
  const prop = async (values, summary) => {
    const cur = await call('GET', `/api/v1/agent/objects/${K}/${o.id}`, null, null, AGH);
    return call('POST', `/api/v1/agent/objects/${K}/${o.id}/proposals`, {values, expect_updated_at: cur.updated_at, summary}, null, AGH);
  };
  const j1 = await prop({note: 'final text', size: 5}, 'Clearer wording');
  check(j1.http === 201 && j1.kind === 'obj_patch', 'setup: a proposal ' + j1.http + JSON.stringify(j1.error || ''));

  // ================= the card
  let w = await boot({user: 'alice', hash: 'prop/' + j1.id}), d = w.document;
  let md = await until(() => d.querySelector('.ppm .ppl .ppi') && d.querySelector('.ppm'));
  const rows = md ? [...md.querySelectorAll('.ppl .ppi')].map(r => r.textContent.replace(/\s+/g, ' ').trim()) : [];
  check(rows.length === 2 && rows.some(t => /note/.test(t) && /first draft/.test(t) && /final text/.test(t)) && rows.some(t => /size/.test(t) && /2/.test(t) && /5/.test(t)),
    '#4718: per field the value now -> the proposed one ' + JSON.stringify(rows));
  check(/Proposal by Claude/.test(md?.textContent || '') && /Kick-off/.test(md?.textContent || '') && /Clearer wording/.test(md?.querySelector('.ppsum')?.textContent || ''),
    '#4718: who proposes it, the object, why');
  const ap = md?.querySelector('[data-pp="apply"]');
  check(ap && !ap.disabled && !!ap.querySelector('.thumb svg') && !!md.querySelector('[data-pp="discard"] .thumb svg') && !md.querySelector('.ppc'),
    '#4718: 👍 / 👎, no checkboxes');
  click(w, ap);
  check(await until(async () => (await call('GET', `/api/obj/${K}/${o.id}`)).note === 'final text'), '#4718: 👍 writes the value (server)');
  const ob = await call('GET', `/api/obj/${K}/${o.id}`);
  check(ob.size === 5 && ob.updated_by === 1, '#4718: written as the person ' + JSON.stringify({size: ob.size, by: ob.updated_by}));
  check(await until(() => /2 fields changed/.test(d.querySelector('#toast, .toast')?.textContent || ''), 20), '#4718: the toast names the fields');
  w.close();

  // ================= changed by someone else while the card is open: 409 on the card
  const j2 = await prop({note: 'agent again'});
  w = await boot({user: 'alice', hash: 'prop/' + j2.id}); d = w.document;
  md = await until(() => d.querySelector('.ppm .ppl .ppi') && d.querySelector('.ppm'));
  await call('PATCH', `/api/obj/${K}/${o.id}`, {note: 'changed meanwhile'});
  click(w, md?.querySelector('[data-pp="apply"]'));
  const er = await until(() => { const e = d.querySelector('#pp-err'); return e && !e.hidden && e.textContent; });
  check(/since the proposal/.test(er || ''), '#4718: the card says it was changed since (409) ' + er);
  check((await call('GET', `/api/obj/${K}/${o.id}`)).note === 'changed meanwhile', '#4718: nothing written');
  w.close();

  // ================= opened after the change: the card says so, Accept off
  w = await boot({user: 'alice', hash: 'prop/' + j2.id}); d = w.document;
  md = await until(() => d.querySelector('.ppm .ppl .ppi') && d.querySelector('.ppm'));
  check(md?.querySelector('[data-pp="apply"]')?.disabled === true && /accepting is refused/.test(md?.textContent || '') && /The agent saw: final text/.test(md?.textContent || ''),
    '#4718: a stale card: the hint, what the agent saw, Accept off');
  w.close();

  // ================= Firefox: 390 px
  const j3 = await prop({note: 'a much longer proposed note that goes on and on so the row has to wrap on a phone screen', size: 9}, 'Shorter and clearer');
  await firefox(async ({cmd, ev: fev, nav, ctx, shot}) => {
    await nav(B + 'static/icon.svg');
    await fev('(() => { localStorage.clear(); return 1; })()');
    check(await fev(`fetch('/api/auth/login', {method: 'POST', headers: {'Content-Type': 'application/json', 'X-Requested-With': 'kalmido'}, body: JSON.stringify({username: 'alice', password: 'password123'})}).then(r => r.status)`) === 200, 'Firefox: login');
    await cmd('browsingContext.setViewport', {context: ctx, viewport: {width: 390, height: 844}});
    await nav(B + '#prop/' + j3.id);
    for (let i = 0; i < 30 && !(await fev('!!document.querySelector(".ppm .ppl .ppi")').catch(() => false)); i++) await sleep(300);
    const r = await fev(`(() => { const vw = document.documentElement.clientWidth, card = document.querySelector('.ppm .card').getBoundingClientRect();
      const bad = [...document.querySelectorAll('.ppm .ppl *')].filter(e => { const x = e.getBoundingClientRect(); return x.width && x.right > vw + 1; }).length;
      return {vw, right: card.right, bad}; })()`);
    check(r.right <= r.vw + 1 && !r.bad, '390 px: the card inside the screen ' + JSON.stringify(r));
    await shot('p2623c-card-390.png');
  }, true);

  console.log(`${ok} ok, ${F.length} failed`);
  process.exit(F.length ? 1 : 0);
})().catch(e => { console.log('FAIL: crash', e); process.exit(1); });
