o = read_ovr(d) or ""
check(rc == 0 and "network_mode" not in o and '"127.0.0.1:3050:3040"' in o, f"#4358: the old line goes, the port stays ({rc} {err[:200]} {o})")
own = "services:\n  kalmido:\n    network_mode: bridge\n"
d = folder(own)
rc, _, _ = run(ID + 'DIR="%s"; PORT=3040; write_override' % d)
check(rc == 0 and read_ovr(d) == own, "#4358: an override of your own stays untouched")

