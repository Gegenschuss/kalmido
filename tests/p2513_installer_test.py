LIB = os.path.join(TMP, "lib.sh")
with open(LIB, "w", encoding="utf-8") as f:
    f.write(SH.rstrip()[:-len('main "$@"')])
STUB = os.path.join(TMP, "bin")
os.makedirs(STUB)
CALLS = os.path.join(TMP, "calls")


def stub(name, body):
    p = os.path.join(STUB, name)
    with open(p, "w", encoding="utf-8") as f:
        f.write('#!/bin/sh\necho "%s $*" >> "%s"\n%s\n' % (name, CALLS, body))
    os.chmod(p, os.stat(p).st_mode | stat.S_IXUSR)


def run(code, **env):
    """The functions of install.sh, then CODE; -> (exit code, stdout, stderr)."""
    if os.path.exists(CALLS):
        os.remove(CALLS)
    e = {k: v for k, v in os.environ.items() if not k.startswith(("KALMIDO_", "SSH_"))}
    e.update(PATH=STUB + os.pathsep + e["PATH"], **env)
    r = subprocess.run(["sh", "-c", '. "%s"\n%s' % (LIB, code)], env=e, capture_output=True, text=True, timeout=60)
    return r.returncode, r.stdout, r.stderr


def calls():
    if not os.path.exists(CALLS):
        return ""
    with open(CALLS, encoding="utf-8") as f:
        return f.read()


def folder(override=None):
    d = tempfile.mkdtemp(dir=TMP)
    if override is not None:
        with open(os.path.join(d, "docker-compose.override.yml"), "w", encoding="utf-8") as f:
            f.write(override)
    return d


def read_ovr(d):
    p = os.path.join(d, "docker-compose.override.yml")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        return f.read()


