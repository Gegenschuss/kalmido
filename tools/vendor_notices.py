#!/usr/bin/env python3
"""Writes the notices file of a bundled npm library from its installed packages (#4171).

    mkdir /tmp/lic && cd /tmp/lic && npm install mermaid@12.2.0 --ignore-scripts --no-audit --no-fund
    python3 tools/vendor_notices.py /tmp/lic/node_modules mermaid > static/vendor/mermaid/THIRD_PARTY

Walks the `dependencies` of the root package (no devDependencies, no peer / optional ones), the way node resolves them (own
node_modules, then the folders above). Lists name, version and license of every package, then the license / copyright texts;
packages with an identical text share one block. Standard library only; run it OUTSIDE the folder with the packages.
"""
import hashlib
import json
import os
import re
import sys

TEXT_RE = re.compile(r"^(licen[sc]e|copying|notice)([-_.].*)?$", re.I)


def find(node_modules, frm, name):
    """Folder of package `name` as seen from package folder `frm` (node's lookup), or None."""
    d = frm
    while True:
        cand = os.path.join(d, "node_modules", name)
        if os.path.isfile(os.path.join(cand, "package.json")):
            return cand
        parent = os.path.dirname(d)
        if parent == d or len(d) <= len(os.path.dirname(node_modules)):
            break
        d = parent
    cand = os.path.join(node_modules, name)
    return cand if os.path.isfile(os.path.join(cand, "package.json")) else None


def license_of(meta):
    lic = meta.get("license") or meta.get("licenses")
    if isinstance(lic, dict):
        lic = lic.get("type")
    if isinstance(lic, list):
        lic = " OR ".join(x.get("type", "?") if isinstance(x, dict) else str(x) for x in lic)
    return lic or "UNKNOWN"


def texts_of(folder):
    out = []
    for fn in sorted(os.listdir(folder)):
        p = os.path.join(folder, fn)
        if os.path.isfile(p) and TEXT_RE.match(fn) and not fn.lower().endswith((".js", ".json", ".ts")):
            with open(p, encoding="utf-8", errors="replace") as f:
                out.append(f.read().strip())
    return "\n\n".join(out)


def collect(node_modules, root):
    start = find(node_modules, os.path.dirname(node_modules), root)
    if not start:
        sys.exit(f"{root} not found in {node_modules}")
    seen, todo, pkgs = set(), [start], []
    while todo:
        d = todo.pop()
        real = os.path.realpath(d)
        if real in seen:
            continue
        seen.add(real)
        with open(os.path.join(d, "package.json"), encoding="utf-8") as f:
            meta = json.load(f)
        text, lic = texts_of(d), license_of(meta)
        if lic == "UNKNOWN" and "MIT License" in text[:200]:
            lic = "MIT (named in its license file only)"
        pkgs.append((meta.get("name", os.path.basename(d)), meta.get("version", "?"), lic, text))
        for dep in sorted(meta.get("dependencies") or {}):
            sub = find(node_modules, d, dep)
            if sub:
                todo.append(sub)
            else:
                print(f"warning: {dep} (needed by {meta.get('name')}) not installed", file=sys.stderr)
    return sorted(set((n, v, l, t) for n, v, l, t in pkgs), key=lambda x: (x[0].lower(), x[1]))


def render(root, pkgs):
    out = [f"Notices of the packages in the dependency tree of {root} (generated by tools/vendor_notices.py from the npm",
           "packages of the bundled version; the bundle static/vendor/" + root + "/" + root + ".min.js contains the parts of them it uses).",
           "", f"{len(pkgs)} packages", ""]
    for n, v, l, _t in pkgs:
        out.append(f"  {n} {v}  ({l})")
    groups = {}
    for n, v, l, t in pkgs:
        groups.setdefault(hashlib.sha256(t.encode()).hexdigest(), []).append((n, v, l, t))
    for g in sorted(groups.values(), key=lambda g: g[0][0].lower()):
        out += ["", "=" * 78, ", ".join(f"{n} {v}" for n, v, _l, _t in g), "-" * 78, g[0][3] or "(the package carries no license file; license field: " + g[0][2] + ")"]
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    nm = os.path.abspath(sys.argv[1])
    sys.stdout.write(render(sys.argv[2], collect(nm, sys.argv[2])))


if __name__ == "__main__":
    main()
