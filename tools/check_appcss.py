#!/usr/bin/env python3
"""2.476.0 (#3487): static/app.css does not grow any more (like core/schema.py in #3478).

Every package used to append its rules at the end of app.css, so two packages built side by side collided on the same last
lines (the most frequent merge conflict). New rules go elsewhere instead:
  * rules of a module loaded on demand: its own stylesheet static/css/<module>.css (LD_CSS in static/js/lazyload.js; the
    precache list LAZY_CSS in static/sw.js is generated by tools/sw_lists.py)
  * rules needed at start: a file of their own, static/css/start-<topic>.css (one per package / topic); the server sends
    them behind app.css under the same URL (kalmido/core/strip.py with_start_css), name order = cascade order
Changing or deleting lines of app.css stays allowed; only its line count may not rise above APPCSS_MAX_LINES. The limit is
written here once and only ever lowered (never by every package: nobody has to touch this file to add styles).
Each start file must balance its braces and close its comments on its own (a lost "}" would swallow the files after it).

usage: python3 tools/check_appcss.py [--root DIR] [-v]     exit code 1 on an error; also runs inside tools/check_layout.py
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APPCSS_MAX_LINES = 8836  # 01.11.2026, the line count of app.css in main when the rule came in (#3773 added 2 lines meanwhile); lower it when app.css shrinks
WHERE = ("put new rules into static/css/<module>.css (loaded with the module, LD_CSS in static/js/lazyload.js) or, "
         "when they are needed at start, into a file of their own static/css/start-<topic>.css (docs/ARCHITECTURE.md, "
         "\"Styles and start scripts\")")


def css_lines(text):
    return text.count("\n") + (0 if text.endswith("\n") or not text else 1)


def braces(name, text):
    """Errors of one stylesheet on its own: an unclosed comment, a closing brace too many, blocks left open."""
    err = []
    if re.sub(r"/\*.*?\*/", "", text, flags=re.S).count("/*"):
        err.append(f"{name}: a comment is not closed")
        return err
    css, depth, opened = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group()), text, flags=re.S), 0, 0
    for no, line in enumerate(css.split("\n"), 1):
        for ch in line:
            depth += (ch == "{") - (ch == "}")
            if depth < 0:
                err.append(f"{name} line {no}: a closing brace too many")
                depth = 0
        if depth == 0:
            opened = no
    if depth:
        err.append(f"{name}: {depth} block(s) not closed -- the first after line {opened}")
    return err


def errors(root=ROOT, verbose=False):
    err = []
    path = os.path.join(root, "static", "app.css")
    with open(path, encoding="utf-8") as f:
        n = css_lines(f.read())
    if n > APPCSS_MAX_LINES:
        err.append(f"static/app.css grew to {n} lines (limit {APPCSS_MAX_LINES}): app.css takes no new rules any more -- {WHERE}")
    starts = sorted(glob.glob(os.path.join(root, "static", "css", "start-*.css")))
    for p in starts:
        name = "static/css/" + os.path.basename(p)
        if not re.fullmatch(r"start-[a-z0-9][a-z0-9_-]*\.css", os.path.basename(p)):
            err.append(f"{name}: start style files are named start-<topic>.css (lower case letters, digits, - and _)")
        with open(p, encoding="utf-8") as f:
            err += braces(name, f.read())
    if verbose:
        print(f"check_appcss: app.css {n} of {APPCSS_MAX_LINES} lines, {len(starts)} start style file(s), {len(err)} error(s)")
    return err


if __name__ == "__main__":
    args = sys.argv[1:]
    r = args[args.index("--root") + 1] if "--root" in args else ROOT
    e = errors(r, "-v" in args)
    for x in e:
        print("ERROR:", x)
    sys.exit(1 if e else 0)
