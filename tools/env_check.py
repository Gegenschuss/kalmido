#!/usr/bin/env python3
"""2.149.0 D (#2511): every environment variable the server reads is declared in kalmido/core/env.py, and docs/ENV.md
(generated from that registry) is current.

  python3 tools/env_check.py               check (CI lint): exit 1 on an undeclared variable or a stale docs/ENV.md
  python3 tools/env_check.py --write-docs  write docs/ENV.md from the registry
  python3 tools/env_check.py --list        every read variable with its first place (for maintainers)

Static only (no app start, no imports of the app): reads kalmido/**/*.py and app.py as text. A read is os.environ.get /
os.getenv / os.environ[...] / "X" in os.environ with a literal name, or a helper call with "env" in its name and a literal
UPPER_CASE name as first argument (env_bool("X"), _env_int("X", ...)). A name built with an f-string
(os.environ.get(f"KALMIDO_PURGE_{kind}")) needs at least one declared variable with that prefix. Names that only appear in
a lookup table (OIDC_FIELDS) are declared by hand; the check cannot see them and does not complain about them."""
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if "--root" in sys.argv:  # the server code of another checkout (docs/ENV.md stays the one next to this tool)
    ROOT_SRC = os.path.abspath(sys.argv[sys.argv.index("--root") + 1])
else:
    ROOT_SRC = ROOT
DOCS = os.path.join(ROOT, "docs", "ENV.md")
REG = os.path.join(ROOT_SRC, "kalmido", "core", "env.py")

NAME = r"([A-Z][A-Z0-9_]{1,})"
READS = [
    re.compile(r"(?<![\w.])os\.environ\.get\(\s*[\"']" + NAME + r"[\"']"),
    re.compile(r"(?<![\w.])os\.getenv\(\s*[\"']" + NAME + r"[\"']"),
    re.compile(r"(?<![\w.])os\.environ\[\s*[\"']" + NAME + r"[\"']\s*\]"),
    re.compile(r"(?<![\w.])os\.environ\.setdefault\(\s*[\"']" + NAME + r"[\"']"),
    re.compile(r"[\"']" + NAME + r"[\"']\s+(?:not\s+)?in\s+os\.environ\b"),
    re.compile(r"(?<![\w.])[A-Za-z_][A-Za-z0-9_]*env[A-Za-z0-9_]*\(\s*[\"']" + NAME + r"[\"']"),
]
FSTR = re.compile(r"(?<![\w.])os\.(?:environ\.get|getenv)\(\s*f[\"']([A-Z][A-Z0-9_]*)\{")


def sources():
    out = [os.path.join(ROOT_SRC, "app.py")]
    for d, _dirs, files in os.walk(os.path.join(ROOT_SRC, "kalmido")):
        out += [os.path.join(d, f) for f in files if f.endswith(".py")]
    return sorted(p for p in out if os.path.isfile(p))


def reads():
    """{name: first "file:line"} and {f-string prefix: first "file:line"}."""
    found, prefixes = {}, {}
    for p in sources():
        if os.path.abspath(p) == REG:
            continue
        rel = os.path.relpath(p, ROOT_SRC)
        with open(p, encoding="utf-8") as f:
            for n, line in enumerate(f, 1):
                if line.lstrip().startswith("#"):
                    continue
                for rx in READS:
                    for m in rx.finditer(line):
                        found.setdefault(m.group(1), f"{rel}:{n}")
                for m in FSTR.finditer(line):
                    prefixes.setdefault(m.group(1), f"{rel}:{n}")
    return found, prefixes


def registry():
    """The VARS tuple of kalmido/core/env.py, read with ast (no import): [(name, default, doc, group)]."""
    with open(REG, encoding="utf-8") as f:
        tree = ast.parse(f.read(), REG)
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "VARS" for t in node.targets):
            out = []
            for el in node.value.elts:
                args = [ast.literal_eval(a) for a in el.args]
                out.append(tuple(args) + ("",) * (4 - len(args)))
            return out
    raise SystemExit("env_check: no VARS in kalmido/core/env.py")


GROUP_TITLES = (
    ("core", "Core: data, database, address"),
    ("auth", "Login, accounts and proxy"),
    ("security", "Server key, encryption and limits"),
    ("notify", "Notifications and push"),
    ("mail", "E-mail"),
    ("files", "Files, scanning and text recognition"),
    ("backup", "Backups and restore"),
    ("office", "Office"),
    ("integrations", "Integrations, calendars, webhooks"),
    ("agents", "Agents and assistant"),
    ("workers", "Background work and timing"),
    ("hosting", "Hosting, retention and quotas"),
    ("test", "Tests and development (not for production)"),
)


def render(regs):
    lines = ["# Environment variables", "",
             "<!-- generated by tools/env_check.py --write-docs from kalmido/core/env.py - do not edit by hand -->", "",
             "Every variable the server reads, with its default. Set them in `.env` (Docker Compose) or the environment of the",
             "container. Switches accept `1`, `true`, `yes`, `on` (on) and `0`, `false`, `no`, `off` (off), in any case;",
             "an empty value counts as unset. See [SELF-HOSTING.md](SELF-HOSTING.md) for the context of each area.", ""]
    titles = dict(GROUP_TITLES)
    order = [g for g, _ in GROUP_TITLES] + sorted({r[3] for r in regs} - set(titles))
    for g in order:
        rows = sorted((r for r in regs if r[3] == g), key=lambda r: r[0])
        if not rows:
            continue
        lines += [f"## {titles.get(g, g)}", "", "| Variable | Default | Meaning |", "|---|---|---|"]
        for name, default, doc, _g in rows:
            d = "(empty)" if default in ("", None) else str(default).replace("|", "\\|")
            lines.append(f"| `{name}` | `{d}` | {doc.replace('|', chr(92) + '|')} |")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    found, prefixes = reads()
    if "--list" in argv:
        for k in sorted(found):
            print(f"{k}\t{found[k]}")
        for k in sorted(prefixes):
            print(f"{k}*\t{prefixes[k]}")
        return 0
    regs = registry()
    names = [r[0] for r in regs]
    if "--write-docs" in argv:
        with open(DOCS, "w", encoding="utf-8") as f:
            f.write(render(regs))
        print(f"env_check: wrote {os.path.relpath(DOCS, ROOT)} ({len(regs)} variables)")
        return 0
    bad = []
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        bad.append("declared twice in kalmido/core/env.py: " + ", ".join(dup))
    for r in regs:
        if not r[2] or not r[3]:
            bad.append(f"{r[0]}: needs a doc sentence and a group in kalmido/core/env.py")
    known = set(names)
    for k in sorted(set(found) - known):
        bad.append(f"{k} ({found[k]}) is read but not declared in kalmido/core/env.py")
    for pre in sorted(prefixes):
        if not any(n.startswith(pre) for n in known):
            bad.append(f"{pre}* ({prefixes[pre]}) is read with a built name but no {pre}... variable is declared")
    try:
        with open(DOCS, encoding="utf-8") as f:
            cur = f.read()
    except OSError:
        cur = ""
    if cur != render(regs):
        bad.append("docs/ENV.md is not current: python3 tools/env_check.py --write-docs")
    for b in bad:
        print("env_check:", b)
    if bad:
        return 1
    print(f"env_check: ok ({len(found)} variables read, {len(regs)} declared)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
