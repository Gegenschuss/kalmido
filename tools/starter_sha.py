#!/usr/bin/env python3
"""2.380 G (#3390): mcp/starter_sha256.txt -- the SHA-256 of the agent starter files (mcp/starter_files.txt and every file it
lists), one "<sha256>  <name>" line each (the sha256sum format). The image carries it (Dockerfile), the server sends it in the
answer of POST /api/agent-setup/redeem (starter_sha256) and static/agent/setup.sh / setup.ps1 refuse a downloaded starter file
whose hash differs, so a changed file on the download address is never installed.
usage: python3 tools/starter_sha.py           write the file (after changing a starter file)
       python3 tools/starter_sha.py --check   exit 1 when the file does not match the starter files (CI lint)"""
import hashlib
import os
import sys

MCP = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "mcp")
OUT = os.path.join(MCP, "starter_sha256.txt")
HEAD = ("# 2.380 G (#3390): generated by tools/starter_sha.py from starter_files.txt -- do not edit by hand; CI checks it\n")


def names():
    out = ["starter_files.txt"]
    with open(os.path.join(MCP, "starter_files.txt"), encoding="utf-8") as f:
        for ln in f:
            n = ln.split("#", 1)[0].strip()
            if n and n not in out:
                out.append(n)
    return out


def render():
    lines = []
    for n in names():
        with open(os.path.join(MCP, n), "rb") as f:
            lines.append(f"{hashlib.sha256(f.read()).hexdigest()}  {n}\n")
    return HEAD + "".join(lines)


def main(argv):
    want = render()
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                have = f.read()
        except OSError:
            have = ""
        if have != want:
            print("starter_sha: mcp/starter_sha256.txt does not match the starter files -- run python3 tools/starter_sha.py")
            return 1
        print(f"starter_sha: {len(names())} files ok")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(want)
    print(f"starter_sha: wrote {len(names())} hashes to mcp/starter_sha256.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
