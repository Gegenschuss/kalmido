"""2.392.2 (#3366): a job for several tasks, its continuation, the watchdog's findings (agents/watch.py).

agent_job_tasks = the tasks of a job (agent_jobs.task_id stays its first task for older clients; a job of one task has no row
here). agent_jobs.continue_of = the job this one continues (the same agent's), NULL = none. job_watch = what the watchdog told
once per case: kind job_stalled (a running job without progress, ref "<job id>@<its updated_at>") or branch_stranded (a branch
of a task without a merge and without an open job, ref "<task id>:<connection id>:<branch>@<sha>"); user_id = the person told,
cleared_at = the case is over. New tables and a column only: older versions ignore them."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS agent_job_tasks (
  job_id BIGINT NOT NULL REFERENCES agent_jobs(id) ON DELETE CASCADE, task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  pos BIGINT NOT NULL DEFAULT 0, PRIMARY KEY (job_id, task_id));
CREATE INDEX IF NOT EXISTS agent_job_tasks_task ON agent_job_tasks(task_id);
CREATE TABLE IF NOT EXISTS job_watch (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL, ref TEXT NOT NULL,
  agent_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  job_id BIGINT REFERENCES agent_jobs(id) ON DELETE CASCADE, task_id BIGINT REFERENCES tasks(id) ON DELETE CASCADE,
  detail TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, cleared_at TEXT);
CREATE UNIQUE INDEX IF NOT EXISTS job_watch_case ON job_watch(kind, ref);
CREATE INDEX IF NOT EXISTS job_watch_user ON job_watch(user_id) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS job_watch_agent ON job_watch(agent_id);
CREATE INDEX IF NOT EXISTS job_watch_job ON job_watch(job_id) WHERE job_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS job_watch_task ON job_watch(task_id) WHERE task_id IS NOT NULL;
"""
