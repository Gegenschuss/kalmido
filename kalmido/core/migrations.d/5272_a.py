"""2.972.0 (#5272, stage Q4a of the cross-cutting core, analysis #3563, decided 08.11.2026): comments exist once, in the shared
core. obj_comments holds the comments of every kind (kind 'task' = the comments of a task, ref_id = the task); obj_comment_trash
keeps the text of a comment in the trash. They replace comments and comment_trash_text (core/objcomments.py).

Real types only (#5305): the points in time are TIMESTAMPTZ (defaults CURRENT_TIMESTAMP, never now(): a restore refuses a call
in a default), mentions BIGINT[], the task's extras (suggestion, answer buttons, the answer, portal, a rule's name) keys of
extra JSONB, set only when there is a value.

ref_id has no foreign key (kind names its table): the trigger kalmido_ocm_task_gone deletes a task's comments when the task is
deleted for good -- what ON DELETE CASCADE did on comments. org_id is filled by the trigger kalmido_orw_obj_comments
(core/orgrows.py) from the task's project, like before. The reactions of a comment (obj_reactions, target 'comment') go with it
(kalmido_orx_gone of 5269_a, now on this table).

The move: core/db.py init_db calls core/objcomments.py ocm_move before AFTER runs -- the rows of comments and
comment_trash_text go into the new tables with their ids (task_seen.seen_id, notifications.comment_id, attachments.comment_id,
obj_reactions and git_issue_comments.comment_id keep pointing at the right comment), the identity goes on after the highest id,
the foreign keys of git_issue_comments and cmt_fts are moved over to obj_comments; then the two tables are dropped. One-way: a
version before 2.972 makes comments again, empty (its schema.py), and shows no comments until this version is back (its next
start moves what was written meanwhile, an id already taken there is left out); a backup restores the old state.
"""
SCHEMA = """
CREATE TABLE IF NOT EXISTS obj_comments (  -- 2.972.0 (#5272): one comment of the shared core on an object (kind, ref_id)
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL,
  ref_id BIGINT NOT NULL, -- no FK: a row of the kind's table (task -> tasks); kalmido_ocm_task_gone deletes with it
  org_id BIGINT REFERENCES orgs(id) ON DELETE SET NULL,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL, -- the author; NULL = written from outside (ext_name) or the account is gone
  ext_name TEXT,
  parent_id BIGINT, -- no FK: the answered comment of the same object (a deleted one stays a quote "deleted")
  body TEXT NOT NULL DEFAULT '',
  mentions BIGINT[] NOT NULL DEFAULT '{}',
  extra JSONB NOT NULL DEFAULT '{}',
  client_ref TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  edited_at TIMESTAMPTZ,
  deleted_at TIMESTAMPTZ,
  deleted_by BIGINT); -- no FK: who put it into the trash (the account may be gone by then)
CREATE INDEX IF NOT EXISTS ix5272_obj_comments_ref ON obj_comments(kind, ref_id);
CREATE INDEX IF NOT EXISTS ix5272_obj_comments_user ON obj_comments(user_id, created_at);
CREATE INDEX IF NOT EXISTS ix5272_obj_comments_created ON obj_comments(created_at);
CREATE INDEX IF NOT EXISTS ix5272_obj_comments_org ON obj_comments(org_id) WHERE org_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ix5272_obj_comments_client_ref ON obj_comments(kind, ref_id, user_id, client_ref) WHERE client_ref IS NOT NULL;
CREATE TABLE IF NOT EXISTS obj_comment_trash (  -- 2.972.0 (#5272): the kept text of a comment in the trash (until the trash run / a restore)
  comment_id BIGINT PRIMARY KEY REFERENCES obj_comments(id) ON DELETE CASCADE,
  body TEXT NOT NULL DEFAULT '',
  mentions BIGINT[] NOT NULL DEFAULT '{}',
  enc TEXT);
CREATE OR REPLACE FUNCTION kalmido_ocm_task_gone() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE prev text := current_setting('app.role', true);
BEGIN
  PERFORM set_config('app.role', 'system', true);
  DELETE FROM obj_comments WHERE kind = 'task' AND ref_id = OLD.id;
  PERFORM set_config('app.role', COALESCE(prev, ''), true);
  RETURN NULL;
END $$;
CREATE OR REPLACE TRIGGER kalmido_ocm_task_gone AFTER DELETE ON tasks FOR EACH ROW EXECUTE FUNCTION kalmido_ocm_task_gone();
CREATE OR REPLACE TRIGGER kalmido_orx_gone_comment AFTER DELETE ON obj_comments FOR EACH ROW EXECUTE FUNCTION kalmido_orx_gone('comment');
"""
