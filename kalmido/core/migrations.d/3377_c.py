"""2.394.0 C (#3377): the two-way issue sync of a repository connection (kalmido/integrations/git_sync.py).
git_conns: issue_since = the newest issue update the sync has read (the next round asks for what came after it), issue_on_at
= when the sync was switched on (only issues opened after it become new tasks), issue_rw = the token may write issues
(1 yes, 0 no: read only, -1 not checked yet), issue_error / issue_synced_at = what the settings show.
git_issue_links: snap = the last synced state per field (JSON: title, body, state, labels, the notes' tail), dirty = which
fields were changed here and when (JSON), push_due = when the collected local changes go out (epoch seconds, 0 = nothing).
git_issue_comments = which comment came from / went to which issue comment (no echo, nothing twice; remote_id NULL = still
to be sent). 2.394.0 D (#3377 review): push_err / push_fails = the error of the last failed sends of a link and how often
in a row (after GSY_FAIL_MAX the same error the sync gives up on it until the task changes again). git_issue_gone = issues whose task was deleted or moved away: never a task again. Older versions ignore all."""
