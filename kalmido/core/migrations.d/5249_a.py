"""2.747.0 (#5249): undo across devices, stage 1 -- the core's undo steps grouped per account (kalmido/core/undogroups.py).
undo_groups = one step of a person as the app lists it ("Letzte Schritte"): the area, a label (an i18n key + its values,
translated for the reader), the device, the state (done | undone | partial | barrier | toobig | noaccess), the number of its
parts and their bytes; token = the header X-Kalmido-Undo-Group that bundles the parts of several requests (10 seconds).
obj_undo gets group_id (the group of the part; NULL = an editor session's step only), mode (snap | diff | ref; snap = the
raw copy of before) and bytes (the size of the copy). New table and columns only: older versions ignore them."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS undo_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE, area TEXT NOT NULL DEFAULT 'other', label_key TEXT NOT NULL DEFAULT '',
  label_args TEXT NOT NULL DEFAULT '[]', device TEXT NOT NULL DEFAULT '', token TEXT NOT NULL DEFAULT '',
  state TEXT NOT NULL DEFAULT 'done', parts BIGINT NOT NULL DEFAULT 0, bytes BIGINT NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
"""
MIGRATIONS = [
    ("obj_undo", "group_id", "ALTER TABLE obj_undo ADD COLUMN IF NOT EXISTS group_id BIGINT"),  # no FK: core/undogroups.py removes a group's parts itself (a session's part stays, unlinked)
    ("obj_undo", "mode", "ALTER TABLE obj_undo ADD COLUMN IF NOT EXISTS mode TEXT NOT NULL DEFAULT 'snap'"),
    ("obj_undo", "bytes", "ALTER TABLE obj_undo ADD COLUMN IF NOT EXISTS bytes BIGINT NOT NULL DEFAULT 0"),
]
AFTER = [
    "CREATE INDEX IF NOT EXISTS undo_groups_user ON undo_groups(user_id, created_at DESC)",
    "CREATE INDEX IF NOT EXISTS undo_groups_created ON undo_groups(created_at)",
    "CREATE INDEX IF NOT EXISTS obj_undo_group ON obj_undo(group_id)",
]
