"""2.581.0 (#4803): document flows ("Abläufe", kalmido/docs/flows.py). The flows themselves stay in doc_rules.data (sealed JSON:
trigger, filters, actions -- an old rule reads as a flow with the trigger "received"). doc_flow_runs = one run of one flow on one
document: trig (received | changed | scheduled), stamp (scheduled: the day it was due from, at most one run per flow, document and
stamp), state (done | skip = a scheduled flow looked and its filters did not hold), data = sealed JSON of the values before / after
(the undo), task_id = a task the run made, hook = the webhook call of the run ('' none | wait | done | failed | blocked) with its
tries, undone_at = taken back. New table only: older versions ignore it."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS doc_flow_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE, ws TEXT NOT NULL,
  node_id BIGINT NOT NULL REFERENCES fs_nodes(id) ON DELETE CASCADE, rule_id BIGINT, -- no FK: a run stays (and can be taken back) after its flow was deleted
  trig TEXT NOT NULL, stamp TEXT NOT NULL DEFAULT '', state TEXT NOT NULL DEFAULT 'done', data TEXT NOT NULL DEFAULT '',
  task_id BIGINT, by_user BIGINT, -- no FK: the task / the person kept as history
  hook TEXT NOT NULL DEFAULT '', hook_attempt BIGINT NOT NULL DEFAULT 0, hook_next DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL, undone_at TIMESTAMPTZ);
"""
AFTER = [
    "CREATE INDEX IF NOT EXISTS doc_flow_runs_node ON doc_flow_runs(node_id, id)",
    # unique-ok doc_flow_runs_once: a new table of this fragment, no rows before it
    "CREATE UNIQUE INDEX IF NOT EXISTS doc_flow_runs_once ON doc_flow_runs(rule_id, node_id, stamp) WHERE trig='scheduled'",
    "CREATE INDEX IF NOT EXISTS doc_flow_runs_hook ON doc_flow_runs(hook_next) WHERE hook='wait'",
]
