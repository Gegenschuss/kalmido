"""2.609.0 (#3372): own ticket types of an organisation (org_id) or of a person (org_id NULL, owner_id = that person), next to
the built-in bug / feature / task (tasks/ttypes.py). key = what tasks.ttype stores (lower case, unique per scope), tpl = the note
template of a new ticket of this type (a project's own one in lists.ticket_tpl wins), enabled = offered (0 = kept, not offered).
lists.ttypes = the types a project offers (json list of keys; '' = all of its workspace). New table and column only: older
versions ignore them (a task of an own type shows no type chip there)."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS ticket_types (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE,
  owner_id BIGINT REFERENCES users(id) ON DELETE CASCADE, key TEXT NOT NULL, name TEXT NOT NULL, icon TEXT NOT NULL DEFAULT '',
  color TEXT NOT NULL DEFAULT '', tpl TEXT NOT NULL DEFAULT '', sort BIGINT NOT NULL DEFAULT 0, enabled BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS ticket_types_org_key ON ticket_types(org_id, key) WHERE org_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ticket_types_own_key ON ticket_types(owner_id, key) WHERE org_id IS NULL;
CREATE INDEX IF NOT EXISTS ticket_types_owner ON ticket_types(owner_id) WHERE owner_id IS NOT NULL;
"""
