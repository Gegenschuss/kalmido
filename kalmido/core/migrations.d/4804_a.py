"""2.581.0 (#4804): documents from the own mailbox of a workspace (hub/mailrules.py).

hub_mailbox_rules = the mail rules of one mailbox (box_id -> hub_mailboxes, gone with it): the conditions (folder, sender,
subject, has an attachment, at most max_age days old), the action (attachments as documents, the mail itself as .eml, a
target folder of the documents area, tags, the sender of the mail as the document's sender) and what happens to the mail
afterwards (after: seen | flag | move | none, after_folder for move; delete only with its own switch, default off).
hub_mailbox_docs = the mails of a mailbox the rules handled (mid = a hash of the Message-ID, else of the head; no address):
each mail once per mailbox. No org_id on purpose (like mail_in_seen): the rows hang on their mailbox, the app checks it.
New tables and nullable columns only: older versions ignore them."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS hub_mailbox_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, box_id BIGINT NOT NULL REFERENCES hub_mailboxes(id) ON DELETE CASCADE,
  ws TEXT NOT NULL, name TEXT NOT NULL DEFAULT '', pos BIGINT NOT NULL DEFAULT 0, active BIGINT NOT NULL DEFAULT 1,
  folder TEXT NOT NULL DEFAULT '', from_has TEXT NOT NULL DEFAULT '', subject_has TEXT NOT NULL DEFAULT '',
  need_att BIGINT NOT NULL DEFAULT 0, max_age BIGINT NOT NULL DEFAULT 30, take_files BIGINT NOT NULL DEFAULT 1,
  take_mail BIGINT NOT NULL DEFAULT 0, target_id BIGINT REFERENCES fs_nodes(id) ON DELETE SET NULL, tags JSONB NOT NULL DEFAULT '[]',
  sender_from_mail BIGINT NOT NULL DEFAULT 1, after TEXT NOT NULL DEFAULT 'seen', after_folder TEXT NOT NULL DEFAULT '',
  delete_mail BIGINT NOT NULL DEFAULT 0, hits BIGINT NOT NULL DEFAULT 0, last_hit_at TEXT,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL);
CREATE INDEX IF NOT EXISTS ix4804_rules_box ON hub_mailbox_rules(box_id);
CREATE INDEX IF NOT EXISTS ix4804_rules_target ON hub_mailbox_rules(target_id) WHERE target_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix4804_rules_created_by ON hub_mailbox_rules(created_by) WHERE created_by IS NOT NULL;
CREATE TABLE IF NOT EXISTS hub_mailbox_docs (
  box_id BIGINT NOT NULL REFERENCES hub_mailboxes(id) ON DELETE CASCADE, mid TEXT NOT NULL,
  rule_id BIGINT REFERENCES hub_mailbox_rules(id) ON DELETE SET NULL,
  node_id BIGINT, -- no FK (2.581.0 #4804): the first document made of the mail, a note only (the marker stays when the document goes)
  at TEXT NOT NULL, PRIMARY KEY (box_id, mid));
CREATE INDEX IF NOT EXISTS ix4804_docs_rule ON hub_mailbox_docs(rule_id) WHERE rule_id IS NOT NULL;
"""
