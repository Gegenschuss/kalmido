"""2.823.0 (#4773): the person's own rules of "My tasks" (kalmido/tasks/minerules.py). Personal like user_mine_sections: no
org_id, nobody else sees them, agents neither read nor propose them. A rule only moves a task inside the person's own order
(user_task_order: section_id and pos), never the task, its list or the list's order.

user_mine_rules: trig = due | new | prio | list | ltag, trig_val = the trigger's value ('t' due today, 'n' due today or
overdue, 'o' overdue, 'b<days>' that many days before the due date; the list id of trig list; the list tag id of trig ltag),
conds = JSON {priority?, list_id?, tag_id?} ('' = none), section_id = the person's own section (a deleted one: the rule waits;
the Undo of the deletion points it at the restored one), place = top | bottom of that section, pos = the order of the rules
(the topmost rule that holds wins), dflt = TRUE for the rule made with the sections ("due today or overdue -> Now"; a deleted one
is kept with deleted_at, so it never comes back by itself).
user_mine_rule_runs: once per rule, task and occasion (key: due:<due day>, new, prio, list:<id>, ltag:<id>); a move the person
makes by hand afterwards stays. New tables only: older versions ignore them."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS user_mine_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL DEFAULT '', trig TEXT NOT NULL, trig_val TEXT NOT NULL DEFAULT '', conds TEXT NOT NULL DEFAULT '',
  section_id BIGINT, -- no FK: a deleted section leaves the rule waiting; the Undo of the deletion points it at the restored one
  place TEXT NOT NULL DEFAULT 'top', pos BIGINT NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE,
  dflt BOOLEAN NOT NULL DEFAULT FALSE, deleted_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL);
CREATE TABLE IF NOT EXISTS user_mine_rule_runs (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rule_id BIGINT NOT NULL REFERENCES user_mine_rules(id) ON DELETE CASCADE,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE, key TEXT NOT NULL, at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (rule_id, task_id, key));
"""
