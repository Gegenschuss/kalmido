"""2.557.0 B (#4670): the server agent - an agent whose model Kalmido calls itself (agents/srvagent.py), with the owner's own key.
agent_server = one row per server agent: provider (anthropic), model ('' = the default), instructions (its standing text, like
CLAUDE.md), key_sealed (the provider key, sealed with the server key, purpose srvagent:<agent id>; never served), key_hint (its
last four characters), cursor (the seq of its newest event a run has read), paused (the reason when a run paused it at its usage
limit, '' otherwise: it goes on with the next event once the limit allows it), updated_at / updated_by.
agent_runs = one row per run of a server agent: trigger (the event that started it), state run | done | failed | aborted |
paused, started / ended, steps (model calls), tokens_in / tokens_out, error (a neutral text, never the provider's answer or the
key), model, beat_at (renewed while it runs: a run without a beat is lost), abort_at (Stop pressed: the run ends at its next
step). New tables only: older versions ignore them."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS agent_server (
  agent_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, provider TEXT NOT NULL DEFAULT 'anthropic',
  model TEXT NOT NULL DEFAULT '', instructions TEXT NOT NULL DEFAULT '', key_sealed TEXT NOT NULL DEFAULT '',
  key_hint TEXT NOT NULL DEFAULT '', cursor BIGINT NOT NULL DEFAULT 0, paused TEXT NOT NULL DEFAULT '', updated_at TEXT NOT NULL DEFAULT '', updated_by BIGINT);
CREATE TABLE IF NOT EXISTS agent_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, agent_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  trigger TEXT NOT NULL DEFAULT '', state TEXT NOT NULL DEFAULT 'run', started TEXT NOT NULL, ended TEXT,
  steps BIGINT NOT NULL DEFAULT 0, tokens_in BIGINT NOT NULL DEFAULT 0, tokens_out BIGINT NOT NULL DEFAULT 0,
  error TEXT NOT NULL DEFAULT '', model TEXT NOT NULL DEFAULT '', beat_at TEXT, abort_at TEXT);
CREATE INDEX IF NOT EXISTS agent_runs_agent ON agent_runs(agent_id, id);
CREATE INDEX IF NOT EXISTS agent_runs_running ON agent_runs(state) WHERE state='run';
"""
