"""2.575.0 (#3778): own module cards (accounts/modcards.py). module_cards = a card: org_id NULL = a person's private card
(user_id = the owner), else a card of the organisation (user_id NULL); mods = csv of its modules, known = csv of the modules
there were when it was saved (a later one is "new" on it), dflt = 1 the organisation's default card (for everybody without an
assignment). module_card_people = the members an organisation's card is assigned to. New tables only: older versions
ignore them (no cap, as before)."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS module_cards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE, name TEXT NOT NULL, icon TEXT NOT NULL DEFAULT 'grid',
  mods TEXT NOT NULL DEFAULT '', known TEXT NOT NULL DEFAULT '', dflt BIGINT NOT NULL DEFAULT 0,
  created_by BIGINT, -- no FK: who made it, kept when that account is gone
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS module_card_people (
  card_id BIGINT NOT NULL REFERENCES module_cards(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, PRIMARY KEY (card_id, user_id));
"""
AFTER = [
    "CREATE INDEX IF NOT EXISTS module_cards_org ON module_cards(org_id)",
    "CREATE INDEX IF NOT EXISTS module_cards_user ON module_cards(user_id)",
    "CREATE INDEX IF NOT EXISTS module_card_people_user ON module_card_people(user_id)",
]
