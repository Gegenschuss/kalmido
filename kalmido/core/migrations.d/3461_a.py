"""2.666.0 (#3461): double-entry bookkeeping (office/ledger_dbl.py): the bookings a person enters by hand and the ones the year-end
closing writes. Everything else of the journal is worked out from the documents on every look (invoices, receipts, payments, bank,
cash book, cards, depreciation) and never copied. A row = one booking with one debit and one credit account (debit = credit);
kind 'manual' = an adjusting entry (accruals, provisions, corrections), 'open' = an opening entry of the year (by hand for the
first year, else written by the closing of the year before), 'close' = the mark that the year is closed (amount = its result,
no accounts). text is encrypted at rest (core/orgcrypt.py). The choice EUeR / balance sheet lives in the office settings
(profit_method, set only by its own route). A new table only: older versions ignore it."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS office_ledger_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id BIGINT NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
  year BIGINT NOT NULL, kind TEXT NOT NULL DEFAULT 'manual', day TEXT NOT NULL DEFAULT '',
  debit TEXT NOT NULL DEFAULT '', credit TEXT NOT NULL DEFAULT '', amount TEXT NOT NULL DEFAULT '0.00',
  text TEXT NOT NULL DEFAULT '', ref TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL, created_by BIGINT, updated_at TEXT NOT NULL, updated_by BIGINT);
"""
AFTER = [
    "CREATE INDEX IF NOT EXISTS office_ledger_entries_year ON office_ledger_entries(org_id, year, kind)",
]
