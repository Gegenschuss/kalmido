"""2.558.0 (#4709): the shared core, stage 1 (kalmido/core/objects.py, kalmido/core/writes.py, docs/dev/kern.md).
obj_history = the change history of a core object (kind + ref_id = the registered kind and the object's id; vals_before /
vals_after = JSON of the changed fields; agent = 1 when an agent wrote; one row per person and object merges the changes of
ten minutes). obj_undo = the session undo steps of a core object (like office_undo, office/undo.py). obj_revoked = what a
revocation took away (src = the table, row_json = the row as it was): a share taken back by hand, or the rows obj_revoke_person
removes when a person leaves an organisation, is demoted, the organisation retires; obj_share_restore puts a row back.
fs_shares.by_role = the role of who made the share at that time (owner | admin | member ...), written only by the core.
New tables and a nullable column only: older versions ignore them."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS obj_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL, ref_id BIGINT NOT NULL, -- no FK: the id of a row of the kind's own table (kind names it)
  org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE, user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  agent BIGINT NOT NULL DEFAULT 0, action TEXT NOT NULL DEFAULT 'update', vals_before TEXT NOT NULL DEFAULT '{}',
  vals_after TEXT NOT NULL DEFAULT '{}', created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS obj_undo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, sess TEXT NOT NULL, kind TEXT NOT NULL, ref_id BIGINT NOT NULL, -- no FK: ref_id = a row of the kind's table
  seq BIGINT NOT NULL DEFAULT 1, state TEXT NOT NULL DEFAULT 'done', snap TEXT NOT NULL DEFAULT '{}', fp_before TEXT NOT NULL DEFAULT '',
  fp_after TEXT NOT NULL DEFAULT '', redo TEXT, fp_undone TEXT, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS obj_revoked (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, src TEXT NOT NULL, org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE, kind TEXT, ref_id BIGINT, row_json TEXT NOT NULL DEFAULT '{}', -- no FK: ref_id = a row of the kind's table
  reason TEXT NOT NULL DEFAULT '', by_id BIGINT, -- no FK: who revoked, kept as history when that account is gone
  created_at TEXT NOT NULL);
"""
