# 2.485.0 (#3939): support access the client grants on a hosted instance (accounts/supportgrant.py). org_id NULL = the person's
# own account (user_id = that person), else the organisation (user_id = the admin who granted it). Ends at ends_at or earlier
# (ended_at, ended_by). uses = what the operator did with it, JSON [{at, by, m, r, s}] (newest last, at most SGA_USES_MAX):
# method, route pattern and status only, never values. New table only: older versions ignore it.
SCHEMA = """
CREATE TABLE IF NOT EXISTS support_grants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE, created_at TIMESTAMPTZ NOT NULL, ends_at TEXT NOT NULL, ended_at TEXT,
  ended_by BIGINT REFERENCES users(id) ON DELETE SET NULL, uses JSONB NOT NULL DEFAULT '[]');
CREATE INDEX IF NOT EXISTS support_grants_user ON support_grants(user_id);
CREATE INDEX IF NOT EXISTS support_grants_org ON support_grants(org_id) WHERE org_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS support_grants_ended_by ON support_grants(ended_by) WHERE ended_by IS NOT NULL;
"""
