"""2.550.0 (#4528): the trash of custom fields. Deleting a field (lists/fields.py field_delete) no longer drops its values for
good at once: the field's row (definition) and every value of it (also of tasks in the trash) wait here as JSON, the live rows
go as before (so no reader of list_fields / task_field_values has to skip anything). Undo and "Restore" in the project
settings (owner and project admins) put the field back with its id and the values of the tasks that still exist in the
project; after the trash period the trash run (files/trashpurge.py TP_PLAIN) deletes the row (one-way). The project cascades.
A new table only: older versions ignore it (a field deleted under the new version stays deleted there too)."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS field_trash (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, list_id BIGINT NOT NULL REFERENCES lists(id) ON DELETE CASCADE,
  field_id BIGINT NOT NULL, name TEXT NOT NULL DEFAULT '', type TEXT NOT NULL DEFAULT '', def TEXT NOT NULL DEFAULT '{}',
  vals TEXT NOT NULL DEFAULT '[]', n BIGINT NOT NULL DEFAULT 0, grouped BIGINT NOT NULL DEFAULT 0,
  deleted_by BIGINT REFERENCES users(id) ON DELETE SET NULL, deleted_at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS field_trash_list ON field_trash(list_id);
CREATE INDEX IF NOT EXISTS field_trash_by ON field_trash(deleted_by) WHERE deleted_by IS NOT NULL;
CREATE INDEX IF NOT EXISTS field_trash_at ON field_trash(deleted_at);
"""
