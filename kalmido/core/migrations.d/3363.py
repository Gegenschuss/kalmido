"""2.488.0 (#3363): the hosted MCP access with OAuth 2.1 (agents/mcpremote.py).

oauth_clients = clients that registered themselves (RFC 7591, public clients without a secret): client_id (random, public),
name, redirect_uris (JSON list, compared exactly), created_at, reg_ip (the counter key of the address that registered it).
oauth_codes = authorization codes, only as SHA-256 (code_hash): one-time (used_at), valid until expires_at (10 min); the code
challenge (S256), the redirect URI and the resource of the request, the person who agreed (user_id) and the agent chosen
(agent_id); grant_id = the access made from it (a second use revokes that access).
oauth_grants = an access given on the consent page: client, agent, the person who agreed, created_at, last_used_at; the
current access token is an api_tokens row of the agent (token_id, made by agents/admin.py agent_token_new, 1 h); the refresh
token only as SHA-256 (refresh_hash, rotated at every use; prev_refresh_hash = the one before, a reuse revokes the access),
refresh_expires_at; revoked_at = revoked (Settings > Agents, POST /oauth/revoke). New tables only: older versions ignore them."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS oauth_clients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id TEXT NOT NULL UNIQUE, name TEXT NOT NULL DEFAULT '',
  redirect_uris TEXT NOT NULL DEFAULT '[]', created_at TEXT NOT NULL, reg_ip TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS oauth_grants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id TEXT NOT NULL REFERENCES oauth_clients(client_id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, agent_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_id BIGINT REFERENCES api_tokens(id) ON DELETE SET NULL, refresh_hash TEXT, prev_refresh_hash TEXT, refresh_expires_at TEXT,
  created_at TEXT NOT NULL, last_used_at TEXT, revoked_at TEXT);
CREATE UNIQUE INDEX IF NOT EXISTS oauth_grants_refresh ON oauth_grants(refresh_hash) WHERE refresh_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS oauth_grants_prev ON oauth_grants(prev_refresh_hash) WHERE prev_refresh_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS oauth_grants_token ON oauth_grants(token_id) WHERE token_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS oauth_grants_user ON oauth_grants(user_id);
CREATE INDEX IF NOT EXISTS oauth_grants_agent ON oauth_grants(agent_id);
CREATE INDEX IF NOT EXISTS oauth_grants_client ON oauth_grants(client_id);
CREATE TABLE IF NOT EXISTS oauth_codes (
  code_hash TEXT PRIMARY KEY, client_id TEXT NOT NULL REFERENCES oauth_clients(client_id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, agent_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  redirect_uri TEXT NOT NULL, challenge TEXT NOT NULL, resource TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL, used_at TEXT, grant_id BIGINT REFERENCES oauth_grants(id) ON DELETE SET NULL);
CREATE INDEX IF NOT EXISTS oauth_codes_client ON oauth_codes(client_id);
CREATE INDEX IF NOT EXISTS oauth_codes_user ON oauth_codes(user_id);
CREATE INDEX IF NOT EXISTS oauth_codes_agent ON oauth_codes(agent_id);
CREATE INDEX IF NOT EXISTS oauth_codes_grant ON oauth_codes(grant_id) WHERE grant_id IS NOT NULL;
"""
