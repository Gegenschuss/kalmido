"""2.947.0 (#5275, stage Q5a of the cross-cutting core, analysis #3563, decided 08.11.2026): tags exist once, in the shared core
(core/objtags.py). obj_tags is one tag of a scope (user | list | org | ws: a person's own, a project's, an organisation's label,
a file workspace's); obj_tag_links puts a tag on an object (kind, obj_id). This stage moves the project tags (list_tags +
task_list_tags) and the labels of an organisation (org_tags) over; an organisation's label now sits on the task itself (no copy
per project any more). Personal tags (task_tags, stage Q5b) and the tags of the file store (doc_tags, stage Q5c) come later --
the table takes their scopes already. Only real types (#5305): TIMESTAMPTZ.

scope_id is TEXT: the id of the list / organisation / person as text, or the workspace key of the file store ("o:3"). org_id is
set for the scope org only (row-level security: an organisation's labels are seen by its members only); a project's tags have
none, as list_tags had none -- the project's own check (need_list) guards them. A tag's name is unique per scope under lower().

No foreign key on the polymorphic columns: kalmido_otg_gone deletes a project's tags when the project row is deleted for good
(what ON DELETE CASCADE of list_tags did) and a task's links when the task row is deleted for good (task_list_tags' cascade);
2.973.0 (#5656): a personal tag (scope user) left without any link then goes as well (task_tags' cascade took the tag itself);
an organisation's labels go with the organisation (org_id ON DELETE CASCADE).

Review F1 / F6 (2.947.0): a project that changes its organisation -- any way that writes lists.org_id (the list dialog, a folder,
"Used for" making it private, a member leaving, the importer) -- runs kalmido_otg_org_moved: the old organisation's labels on its
tasks become project tags of the project (found / made by name, the label's colour; the project's rules and shared views follow,
kalmido_otg_rekey), and a project tag named like a label of the new organisation becomes that label (kalmido_otg_joined). An
organisation deleted for good does the first for each of its projects before its labels go (BEFORE DELETE on orgs). The functions
switch to app.role 'system' for their own statements (the mover may see the old organisation no more) and back. The triggers
themselves are made by core/db.py init_db after mig_apply (core/objtags.py OTG_ORG_TRIGGERS): lists.org_id is a MIGRATIONS
step of schema.py, so a fresh database has no such column while the fragments' SCHEMA runs (review N1).

The move: core/db.py init_db calls core/objtags.py otg_move before AFTER runs -- the rows of the old tables go into the core (a
project tag keeps its id, so rules and shared views that name it stay valid; a label's copies in the projects become the label
itself, the rules / shared views naming a copy are rewritten to the label), then the three tables are dropped. One-way: a version
before 2.947 makes list_tags / task_list_tags again, empty (its schema.py), and shows no project tags and no labels until this
version is back (its next start moves what was written meanwhile); a backup restores the old state.
"""
SCHEMA = """
CREATE TABLE IF NOT EXISTS obj_tags (  -- 2.947.0 (#5275): one tag of a scope (core/objtags.py)
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope_kind TEXT NOT NULL CHECK (scope_kind IN ('user', 'list', 'org', 'ws')),
  scope_id TEXT NOT NULL, -- the person / list / organisation id as text, or a workspace key; no FK: kalmido_otg_gone deletes with the scope
  org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE, -- the scope org only (row-level security); NULL for the other scopes
  name TEXT NOT NULL,
  color TEXT NOT NULL DEFAULT '',
  sort DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP); -- no now(): a restore refuses a call in a default
CREATE UNIQUE INDEX IF NOT EXISTS ix5275_obj_tags_name ON obj_tags(scope_kind, scope_id, lower(name));
CREATE INDEX IF NOT EXISTS ix5275_obj_tags_org ON obj_tags(org_id) WHERE org_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix5275_obj_tags_created_by ON obj_tags(created_by) WHERE created_by IS NOT NULL;
CREATE TABLE IF NOT EXISTS obj_tag_links (  -- 2.947.0 (#5275): a tag on an object of the core
  tag_id BIGINT NOT NULL REFERENCES obj_tags(id) ON DELETE CASCADE,
  kind TEXT NOT NULL, -- the object's kind (task)
  obj_id BIGINT NOT NULL, -- no FK: a row of the kind's table; kalmido_otg_gone deletes with it
  src TEXT NOT NULL DEFAULT 'person' CHECK (src IN ('person', 'agent', 'auto')),
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (tag_id, kind, obj_id));
CREATE INDEX IF NOT EXISTS ix5275_obj_tag_links_obj ON obj_tag_links(kind, obj_id);
CREATE INDEX IF NOT EXISTS ix5275_obj_tag_links_created_by ON obj_tag_links(created_by) WHERE created_by IS NOT NULL;
CREATE OR REPLACE FUNCTION kalmido_otg_gone() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE gone BIGINT[];
BEGIN
  IF TG_ARGV[0] = 'scope' THEN
    DELETE FROM obj_tags WHERE scope_kind = TG_ARGV[1] AND scope_id = OLD.id::text;
  ELSE
    WITH d AS (DELETE FROM obj_tag_links WHERE kind = TG_ARGV[1] AND obj_id = OLD.id RETURNING tag_id)
      SELECT array_agg(tag_id) INTO gone FROM d;
    -- 2.973.0 (#5656): a personal tag lives on its tasks (core/objtags.py otg_user_prune): the last link gone, the tag goes
    DELETE FROM obj_tags ot WHERE ot.id = ANY(gone) AND ot.scope_kind = 'user'
      AND NOT EXISTS (SELECT 1 FROM obj_tag_links k WHERE k.tag_id = ot.id);
  END IF;
  RETURN NULL;
END $$;
CREATE OR REPLACE TRIGGER kalmido_otg_gone_list AFTER DELETE ON lists FOR EACH ROW EXECUTE FUNCTION kalmido_otg_gone('scope', 'list');
CREATE OR REPLACE TRIGGER kalmido_otg_gone_task AFTER DELETE ON tasks FOR EACH ROW EXECUTE FUNCTION kalmido_otg_gone('link', 'task');
CREATE OR REPLACE FUNCTION kalmido_otg_j(v TEXT) RETURNS JSONB LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  RETURN CASE WHEN v IS NULL OR v = '' THEN NULL ELSE v::jsonb END;
EXCEPTION WHEN others THEN
  RETURN NULL;
END $$;
CREATE OR REPLACE FUNCTION kalmido_otg_rekey(lid BIGINT, o BIGINT, n BIGINT) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE list_rules SET trig_val = n::text WHERE list_id = lid AND trig = 'ltag' AND trig_val = o::text;
  UPDATE list_rules SET act_val = jsonb_set(kalmido_otg_j(act_val), '{tag_id}', to_jsonb(n))::text
    WHERE list_id = lid AND act = 'tag' AND jsonb_typeof(kalmido_otg_j(act_val)) = 'object' AND kalmido_otg_j(act_val)->'tag_id' = to_jsonb(o);
  UPDATE list_rules SET more_acts = (SELECT jsonb_agg(CASE WHEN jsonb_typeof(e.x) = 'object' AND e.x->>'kind' = 'tag' AND e.x->'tag_id' = to_jsonb(o)
                                                      THEN jsonb_set(e.x, '{tag_id}', to_jsonb(n)) ELSE e.x END ORDER BY e.i)
                                     FROM jsonb_array_elements(kalmido_otg_j(more_acts)) WITH ORDINALITY AS e(x, i))::text
    WHERE list_id = lid AND jsonb_typeof(kalmido_otg_j(more_acts)) = 'array' AND EXISTS (SELECT 1 FROM jsonb_array_elements(kalmido_otg_j(more_acts)) AS y(x)
      WHERE jsonb_typeof(y.x) = 'object' AND y.x->>'kind' = 'tag' AND y.x->'tag_id' = to_jsonb(o));
  UPDATE list_rules SET conds = jsonb_set(kalmido_otg_j(conds), '{tag_id}', to_jsonb(n))::text
    WHERE list_id = lid AND jsonb_typeof(kalmido_otg_j(conds)) = 'object' AND kalmido_otg_j(conds)->'tag_id' = to_jsonb(o);
  UPDATE public_links SET cv_show = jsonb_set(kalmido_otg_j(cv_show), '{tag}', to_jsonb(n))::text
    WHERE list_id = lid AND cv_show ILIKE '%"tag"%' AND jsonb_typeof(kalmido_otg_j(cv_show)) = 'object' AND kalmido_otg_j(cv_show)->'tag' = to_jsonb(o);
END $$;
CREATE OR REPLACE FUNCTION kalmido_otg_left(lid BIGINT, o BIGINT) RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE r RECORD; i BIGINT; n INTEGER := 0;
BEGIN
  FOR r IN SELECT ot.id, ot.name, ot.color, array_agg(t.id) AS tids FROM obj_tag_links k
           JOIN obj_tags ot ON ot.id = k.tag_id AND ot.scope_kind = 'org' AND ot.scope_id = o::text
           JOIN tasks t ON t.id = k.obj_id AND k.kind = 'task' WHERE t.list_id = lid
           GROUP BY ot.id, ot.name, ot.color, ot.sort ORDER BY ot.sort, ot.id LOOP
    SELECT x.id INTO i FROM obj_tags x WHERE x.scope_kind = 'list' AND x.scope_id = lid::text AND lower(x.name) = lower(r.name);
    IF i IS NULL THEN  -- review N3: a tag of that name made meanwhile (deleting the label converts too): take that one
      INSERT INTO obj_tags(scope_kind, scope_id, name, color, sort, created_at)
        VALUES ('list', lid::text, r.name, r.color, (SELECT COALESCE(MAX(x.sort), 0) + 1 FROM obj_tags x WHERE x.scope_kind = 'list'
                AND x.scope_id = lid::text), CURRENT_TIMESTAMP) ON CONFLICT DO NOTHING RETURNING id INTO i;
      IF i IS NULL THEN
        SELECT x.id INTO i FROM obj_tags x WHERE x.scope_kind = 'list' AND x.scope_id = lid::text AND lower(x.name) = lower(r.name);
      END IF;
    END IF;
    INSERT INTO obj_tag_links(tag_id, kind, obj_id, src, created_by, created_at)
      SELECT i, k.kind, k.obj_id, k.src, k.created_by, k.created_at FROM obj_tag_links k WHERE k.tag_id = r.id AND k.kind = 'task'
      AND k.obj_id = ANY(r.tids) ON CONFLICT DO NOTHING;
    DELETE FROM obj_tag_links k WHERE k.tag_id = r.id AND k.kind = 'task' AND k.obj_id = ANY(r.tids);
    PERFORM kalmido_otg_rekey(lid, r.id, i);
    n := n + 1;
  END LOOP;
  RETURN n;
END $$;
CREATE OR REPLACE FUNCTION kalmido_otg_joined(lid BIGINT, o BIGINT) RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE r RECORD; n INTEGER := 0;
BEGIN
  FOR r IN SELECT p.id AS pid, ot.id AS lb FROM obj_tags p JOIN obj_tags ot ON ot.scope_kind = 'org' AND ot.scope_id = o::text
           AND lower(ot.name) = lower(p.name) WHERE p.scope_kind = 'list' AND p.scope_id = lid::text ORDER BY p.id LOOP
    PERFORM kalmido_otg_rekey(lid, r.pid, r.lb);
    INSERT INTO obj_tag_links(tag_id, kind, obj_id, src, created_by, created_at)
      SELECT r.lb, k.kind, k.obj_id, k.src, k.created_by, k.created_at FROM obj_tag_links k WHERE k.tag_id = r.pid ON CONFLICT DO NOTHING;
    DELETE FROM obj_tags WHERE id = r.pid;
    n := n + 1;
  END LOOP;
  RETURN n;
END $$;
CREATE OR REPLACE FUNCTION kalmido_otg_org_moved() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE prev TEXT;
BEGIN
  IF TG_OP = 'UPDATE' THEN  -- nested: PL/pgSQL does not short-circuit AND, and a row of orgs has no org_id
    IF OLD.org_id IS NOT DISTINCT FROM NEW.org_id THEN
      RETURN NULL;
    END IF;
  END IF;
  prev := current_setting('app.role', true);
  PERFORM set_config('app.role', 'system', true);
  IF TG_OP = 'DELETE' THEN  -- an organisation goes: every project of it keeps the labels on its tasks as project tags
    PERFORM kalmido_otg_left(l.id, OLD.id) FROM lists l WHERE l.org_id = OLD.id;
  ELSE
    IF OLD.org_id IS NOT NULL THEN
      PERFORM kalmido_otg_left(NEW.id, OLD.org_id);
    END IF;
    IF NEW.org_id IS NOT NULL THEN
      PERFORM kalmido_otg_joined(NEW.id, NEW.org_id);
    END IF;
  END IF;
  PERFORM set_config('app.role', COALESCE(prev, ''), true);
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NULL END;
END $$;
-- its two triggers come after the MIGRATIONS steps (lists.org_id is one of them): core/objtags.py OTG_ORG_TRIGGERS, core/db.py init_db
"""
