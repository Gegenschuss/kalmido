"""2.1076.0 (#5271, stage Q3 of the cross-cutting core, analysis #3563, decided 08.11.2026): one table obj_links holds the
links between objects (core/objlinks.py); hub_mail_links, life_device_links, contact_tasks and office_letter_links go.
Real types only (#5305): TIMESTAMPTZ for the points in time, JSONB for the area's extra.

No foreign key on the two sides (src_kind / dst_kind name their tables); instead kalmido_olnk_gone deletes the links of a row
deleted for good -- what ON DELETE CASCADE did on the old tables (a task, an event, a filed e-mail, a contact, a letter, a
file-store node, a piece of office equipment). A row only in the trash keeps its links: the readers answer "gone" (core/objlinks.py
olnk_state) and a restore brings them back.

The move: core/db.py init_db runs core/objhooks.MOVE (core/objlinks.py olnk_move) before AFTER -- the rows of the old tables go
into obj_links (whatever is there: the first start of 2.1076, or the rows a version before wrote after a rollback), then the
four tables are dropped. One-way: a version before 2.1076 would make the old tables again, empty (the back limit refuses it,
core/kernretire.py kern_retire_floor); a backup restores the old state. A device link whose device or equipment was gone
already does not move (it only showed "gone"); the undo steps / history of removed letter links (kind oletlink) go.
"""
SCHEMA = """
CREATE TABLE IF NOT EXISTS obj_links (  -- 2.1076.0 (#5271): a link of the core between two objects
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE,                -- NULL = private (the app checks both sides)
  owner_id BIGINT REFERENCES users(id) ON DELETE CASCADE,             -- set = a person's own link, read only by that person
  src_kind TEXT NOT NULL, src_id BIGINT NOT NULL,                     -- no FK: kalmido_olnk_gone deletes with the row
  dst_kind TEXT NOT NULL, dst_id BIGINT NOT NULL,                     -- no FK: the same (kalmido_olnk_gone)
  rel TEXT NOT NULL DEFAULT 'related', note TEXT NOT NULL DEFAULT '', extra JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, agent_id BIGINT, -- agent_id: no FK, the record stays
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- no now(): a restore refuses a call in a default (admin/backup.py _calls_ok)
  rev BIGINT NOT NULL DEFAULT 1, updated_at TIMESTAMPTZ, updated_by BIGINT,
  deleted_at TIMESTAMPTZ, deleted_by BIGINT,
  UNIQUE (src_kind, src_id, dst_kind, dst_id, rel));
CREATE INDEX IF NOT EXISTS ix5271_obj_links_dst ON obj_links(dst_kind, dst_id);
CREATE INDEX IF NOT EXISTS ix5271_obj_links_trash ON obj_links(deleted_at) WHERE deleted_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix5271_obj_links_owner ON obj_links(owner_id) WHERE owner_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix5271_obj_links_created_by ON obj_links(created_by) WHERE created_by IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ix5271_obj_links_device ON obj_links(src_kind, src_id) WHERE rel = 'device' AND deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ix5271_obj_links_device_eq ON obj_links(owner_id, dst_kind, dst_id) WHERE rel = 'device' AND deleted_at IS NULL;
CREATE OR REPLACE FUNCTION kalmido_olnk_gone() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM obj_links WHERE (src_kind = TG_ARGV[0] AND src_id = OLD.id) OR (dst_kind = TG_ARGV[0] AND dst_id = OLD.id);
  RETURN NULL;
END $$;
CREATE OR REPLACE TRIGGER kalmido_olnk_gone_task AFTER DELETE ON tasks FOR EACH ROW EXECUTE FUNCTION kalmido_olnk_gone('task');
CREATE OR REPLACE TRIGGER kalmido_olnk_gone_event AFTER DELETE ON events FOR EACH ROW EXECUTE FUNCTION kalmido_olnk_gone('event');
CREATE OR REPLACE TRIGGER kalmido_olnk_gone_hub_mail AFTER DELETE ON hub_mails FOR EACH ROW EXECUTE FUNCTION kalmido_olnk_gone('hub_mail');
CREATE OR REPLACE TRIGGER kalmido_olnk_gone_contact AFTER DELETE ON contacts FOR EACH ROW EXECUTE FUNCTION kalmido_olnk_gone('contact');
CREATE OR REPLACE TRIGGER kalmido_olnk_gone_letter AFTER DELETE ON office_letters FOR EACH ROW EXECUTE FUNCTION kalmido_olnk_gone('office_letter');
CREATE OR REPLACE TRIGGER kalmido_olnk_gone_fs_entry AFTER DELETE ON fs_nodes FOR EACH ROW EXECUTE FUNCTION kalmido_olnk_gone('fs_entry');
CREATE OR REPLACE TRIGGER kalmido_olnk_gone_equipment AFTER DELETE ON office_equipment FOR EACH ROW EXECUTE FUNCTION kalmido_olnk_gone('omd_equipment');
"""
