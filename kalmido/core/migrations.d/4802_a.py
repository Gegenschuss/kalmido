"""2.579.0 (#4802): saved views of the documents search (kalmido/docs/dviews.py, kind 'docview' of the shared core,
docs/dev/kern.md). A row = one named combination of the documents search: query = the search's parameters as a query string
(q with its syntax, the filters, the sort; docs/dsearch.py, docs/web.py doc_query), ws = the workspace the search runs in
('all' | 'private' | 'org:<id>'). The rights are the core's: org_id NULL = private (only its owner), org_id = the
organisation = an admin shared it with everyone of it (core/writes.py obj_space_set). The hits are always worked out with the
rights of whoever looks. A new table only: older versions ignore it."""
SCHEMA = """
CREATE TABLE IF NOT EXISTS doc_views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id BIGINT REFERENCES orgs(id) ON DELETE CASCADE,
  owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rev BIGINT NOT NULL DEFAULT 1, created_at TIMESTAMPTZ NOT NULL, created_by BIGINT,
  updated_at TIMESTAMPTZ NOT NULL, updated_by BIGINT, deleted_at TIMESTAMPTZ, deleted_by BIGINT,
  title TEXT NOT NULL DEFAULT '', query TEXT NOT NULL DEFAULT '', ws TEXT NOT NULL DEFAULT 'all');
"""
AFTER = [
    "CREATE INDEX IF NOT EXISTS doc_views_owner ON doc_views(owner_id) WHERE org_id IS NULL",
    "CREATE INDEX IF NOT EXISTS doc_views_org ON doc_views(org_id) WHERE org_id IS NOT NULL",
    "CREATE INDEX IF NOT EXISTS doc_views_trash ON doc_views(deleted_at) WHERE deleted_at IS NOT NULL",
]
